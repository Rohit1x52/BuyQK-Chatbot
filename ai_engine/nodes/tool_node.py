def _get_payment_method(
    state: GraphState,
    args: dict[str, Any],
    entities: dict[str, Any],
) -> str | None:
    """
    Resolve the selected payment method.

    The AI/planner may provide the requested method.

    The backend remains responsible for determining whether
    that method is actually valid/available.
    """

    payment_method = args.get(
        "payment_method"
    )

    if payment_method is None:
        payment_method = args.get(
            "selected_payment_method"
        )

    if payment_method is None:
        payment_method = state.get(
            "selected_payment_method"
        )

    if payment_method is None:
        payment_method = state.get(
            "payment_method"
        )

    if payment_method is None:
        payment_method = entities.get(
            "payment_method"
        )

    if payment_method is None:
        return None

    normalized = str(
        payment_method
    ).strip().lower()

    return normalized or None


# =========================================================
# Quantity
# =========================================================


def _normalize_quantity(
    quantity: Any,
) -> int | None:
    """
    Normalize quantity into a positive integer.
    """

    if quantity is None:
        return None

    if isinstance(
        quantity,
        bool,
    ):
        return None

    try:
        quantity = int(
            quantity
        )
    except (
        TypeError,
        ValueError,
    ):
        return None

    if quantity <= 0:
        return None

    return quantity


# =========================================================
# Order Items
# =========================================================


def _extract_order_items(
    args: dict[str, Any],
    entities: dict[str, Any],
) -> list[dict[str, Any]]:
    """
    Normalize planner tool arguments into backend order items.

    Preferred Phase 2 structure:

        tool_args = {
            "items": [
                {
                    "product_id": 12,
                    "quantity": 2
                }
            ]
        }

    Backward-compatible structures are also accepted.
    """

    raw_items = args.get(
        "items"
    )

    if raw_items is None:
        raw_items = args.get(
            "cart_items"
        )

    if raw_items is None:
        raw_items = entities.get(
            "items"
        )

    if raw_items is None:
        raw_items = entities.get(
            "cart_items"
        )

    # =====================================================
    # Multi-item
    # =====================================================

    if isinstance(
        raw_items,
        list,
    ):

        normalized_items: list[
            dict[str, Any]
        ] = []

        for item in raw_items:

            if not isinstance(
                item,
                dict,
            ):
                continue

            product_id = item.get(
                "product_id"
            )

            product_name = item.get(
                "product_name"
            )

            quantity = _normalize_quantity(
                item.get(
                    "quantity"
                )
            )

            if quantity is None:
                continue

            if (
                product_id is None
                and not _has_value(
                    product_name
                )
            ):
                continue

            normalized_item = {
                "quantity": quantity,
            }

            if product_id is not None:

                normalized_item[
                    "product_id"
                ] = product_id

            else:

                normalized_item[
                    "product_name"
                ] = str(
                    product_name
                ).strip()

            normalized_items.append(
                normalized_item
            )

        return normalized_items

    # =====================================================
    # Single item
    # =====================================================

    product_id = args.get(
        "product_id"
    )

    if product_id is None:
        product_id = entities.get(
            "product_id"
        )

    product_name = args.get(
        "product_name"
    )

    if product_name is None:
        product_name = entities.get(
            "product_name"
        )

    quantity = args.get(
        "quantity"
    )

    if quantity is None:
        quantity = entities.get(
            "quantity"
        )

    quantity = _normalize_quantity(
        quantity
    )

    if quantity is None:
        return []

    if (
        product_id is None
        and not _has_value(
            product_name
        )
    ):
        return []

    item = {
        "quantity": quantity,
    }

    if product_id is not None:

        item[
            "product_id"
        ] = product_id

    else:

        item[
            "product_name"
        ] = str(
            product_name
        ).strip()

    return [
        item
    ]


# =========================================================
# Product Resolution
# =========================================================


def _resolve_product(
    db: Session,
    product_name: str,
) -> tuple[
    Product | None,
    list[Product],
]:
    """
    Resolve a natural-language product name against the
    authoritative Product table.

    This is an execution-time backend lookup.

    The LLM does NOT get to invent the product ID.

    NOTE:
    Product selection logic is intentionally delegated as much
    as possible to product_service.search_products().
    """

    if not _has_value(
        product_name
    ):
        return (
            None,
            [],
        )

    query = str(
        product_name
    ).strip()

    try:

        results = search_products(
            db=db,
            query=query,
        )

    except Exception as exc:

        print(
            "[PRODUCT SEARCH ERROR]",
            type(exc).__name__,
            str(exc),
        )

        return (
            None,
            [],
        )

    if results is None:
        return (
            None,
            [],
        )

    if not isinstance(
        results,
        list,
    ):
        results = [
            results
        ]

    products = [
        product
        for product in results
        if product is not None
    ]

    if not products:
        return (
            None,
            [],
        )

    # -----------------------------------------------------
    # Exact name match first
    # -----------------------------------------------------

    normalized_query = query.strip().casefold()

    exact_matches = []

    for product in products:

        name = _product_name(
            product
        ).casefold()

        if name == normalized_query:
            exact_matches.append(
                product
            )

    if len(exact_matches) == 1:
        return (
            exact_matches[0],
            products,
        )

    if len(exact_matches) > 1:
        return (
            None,
            exact_matches,
        )

    # -----------------------------------------------------
    # If service returned one candidate, accept it.
    # -----------------------------------------------------

    if len(products) == 1:
        return (
            products[0],
            products,
        )

    # -----------------------------------------------------
    # Multiple candidates are ambiguous.
    # -----------------------------------------------------

    return (
        None,
        products,
    )


# =========================================================
# Bill Serialization
