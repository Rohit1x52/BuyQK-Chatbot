def _serialize_bill(
    bill: Any,
) -> dict[str, Any] | None:
    """
    Preserve the complete authoritative backend bill.

    This node does NOT calculate billing.
    """

    if not isinstance(
        bill,
        dict,
    ):
        return None

    return dict(
        bill
    )


# =========================================================
# Tool Result Helpers
# =========================================================


def _error_result(
    error_type: str,
    message: str,
    **extra: Any,
) -> GraphState:
    """
    Build a consistent tool failure response.
    """

    return {
        "tool_result": {
            "success": False,
            "type": error_type,
            "error": message,
            **extra,
        }
    }


# =========================================================
# Tool Node
# =========================================================


def tool_node(
    state: GraphState,
    db: Session,
) -> GraphState:
    """
    Execute the capability selected by the planner/policy/decision
    pipeline.

    ========================================================
    Phase 2 execution contract
    ========================================================

    Planner:
        chooses action/tool

    Policy:
        approves or rejects

    Decision:
        routes

    Tool Node:
        executes

    Backend:
        verifies authoritative facts

    ========================================================

    This node must never bypass backend validation.
    """

    # =====================================================
    # Read approved tool
    # =====================================================

    tool_name = state.get(
        "tool_name"
    )

    if isinstance(
        tool_name,
        str,
    ):
        tool_name = tool_name.strip().casefold()

    entities = _get_entities(
        state
    )

    tool_args = _get_tool_arguments(
        state
    )

    user_id = state.get(
        "user_id"
    )

    checkout_id = state.get(
        "checkout_id"
    )

    print(
        "\n"
        "====================================================\n"
        "[TOOL NODE]\n"
        "====================================================\n"
        f"tool_name  = {tool_name!r}\n"
        f"user_id    = {user_id!r}\n"
        f"tool_args  = {tool_args!r}\n"
        f"checkout_id= {checkout_id!r}\n"
        "====================================================\n"
    )

    # =====================================================
    # No tool
    # =====================================================

    if not tool_name:

        return {
            "tool_result": None,
        }

    # =====================================================
    # Unsupported tool
    # =====================================================

    if tool_name not in SUPPORTED_TOOLS:

        return _error_result(
            "unsupported_tool",
            f"Unsupported tool: {tool_name}",
        )

    # =====================================================
    # SEARCH PRODUCTS
    # =====================================================

    if tool_name == "search_products":

        query = tool_args.get(
            "query"
        )

        if query is None:
            query = tool_args.get(
                "product_name"
            )

        if query is None:
            query = entities.get(
                "product_name"
            )

        if not _has_value(
            query
        ):

            return _error_result(
                "product_search",
                "Product search query is required.",
            )

        try:

            products = search_products(
                db=db,
                query=str(
                    query
                ).strip(),
            )

            if products is None:
                products = []

            if not isinstance(
                products,
                list,
            ):
                products = [
                    products
                ]

            return {
                "tool_result": {
                    "success": True,
                    "type": "product_search",
                    "query": str(
                        query
                    ).strip(),
                    "products": [
                        _serialize_product(
                            product
                        )
                        for product in products
                    ],
                }
            }

        except Exception as exc:

            print(
                "[TOOL search_products ERROR]",
                type(exc).__name__,
                str(exc),
            )

            return _error_result(
                "product_search",
                str(exc),
            )

    # =====================================================
    # LIST SAVED ADDRESSES
    # =====================================================

    if tool_name == "list_saved_addresses":

        if user_id is None:

            return _error_result(
                "address_selection",
                "User ID is required to load saved addresses.",
            )

        user_id_int = _safe_int(
            user_id
        )

        if user_id_int is None:

            return _error_result(
                "address_selection",
                "Invalid user ID.",
            )

        try:

            addresses = get_user_addresses(
                db=db,
                user_id=user_id_int,
            )

            return {
                "tool_result": {
                    "success": True,
                    "type": "address_selection",
                    "addresses": [
                        _serialize_address(
                            address
                        )
                        for address in addresses
                    ],
                    "allow_new": True,
                }
            }

        except Exception as exc:

            print(
                "[TOOL list_saved_addresses ERROR]",
                type(exc).__name__,
                str(exc),
            )

            return _error_result(
                "address_selection",
                str(exc),
            )

    # =====================================================
    # LIST PAYMENT METHODS
    # =====================================================

    if tool_name == "list_payment_methods":

        try:

            from backend.services.order_service import (
                SUPPORTED_PAYMENT_METHODS,
            )

            configured_methods = (
                SUPPORTED_PAYMENT_METHODS
            )

            if configured_methods is None:
                configured_methods = set()

            methods = []

            for method in configured_methods:

                if isinstance(
                    method,
                    dict,
                ):

                    methods.append(
                        dict(method)
                    )

                    continue

                method_id = str(
                    method
                ).strip()

                if not method_id:
                    continue

                methods.append(
                    {
                        "id": method_id,
                        "label": method_id.replace(
                            "_",
                            " ",
                        ).replace(
                            "-",
                            " ",
                        ).title(),
                    }
                )

            return {
                "tool_result": {
                    "success": True,
                    "type": "payment_selection",
                    "methods": methods,
                }
            }

        except ImportError:

            return _error_result(
                "payment_selection",
                "Payment methods are not configured by the backend.",
                methods=[],
            )

        except Exception as exc:

            print(
                "[TOOL list_payment_methods ERROR]",
                type(exc).__name__,
                str(exc),
            )

            return _error_result(
                "payment_selection",
                str(exc),
                methods=[],
            )

    # =====================================================
    # CREATE ORDER
    # =====================================================

    if tool_name == "create_order":

        # -------------------------------------------------
        # User
        # -------------------------------------------------

        user_id_int = _safe_int(
            user_id
        )

        if user_id_int is None:

            return _error_result(
                "order_error",
                "Valid user ID is required.",
            )

        # -------------------------------------------------
        # Items
        # -------------------------------------------------

        order_items = _extract_order_items(
            tool_args,
            entities,
        )

        if not order_items:

            return _error_result(
                "product_required",
                "Product and quantity are required before placing the order.",
            )

        # -------------------------------------------------
        # Address
        # -------------------------------------------------

        address_id = _get_address_id(
            state,
            tool_args,
            entities,
        )

        address_id = _safe_int(
            address_id
        )

        if address_id is None:

            return _error_result(
                "address_selection",
                "Please select a valid delivery address before placing the order.",
            )

        address_valid, address_error = (
            _validate_address(
                db=db,
                user_id=user_id_int,
                address_id=address_id,
            )
        )

        if not address_valid:

            return _error_result(
                "address_selection",
                address_error
                or "Invalid delivery address.",
            )

        # -------------------------------------------------
        # Payment
        # -------------------------------------------------

        payment_method = _get_payment_method(
            state,
            tool_args,
            entities,
        )

        if payment_method is None:

            return _error_result(
                "payment_selection",
                "Please select a payment method before placing the order.",
            )

        # -------------------------------------------------
        # Resolve every product
        # -------------------------------------------------

        resolved_items: list[
            dict[str, Any]
        ] = []

        authoritative_products: list[
            Product
        ] = []

        for item in order_items:

            product_id = item.get(
                "product_id"
            )

            product_name = item.get(
                "product_name"
            )

            quantity = _normalize_quantity(
                item.get(
                    "quantity"
                )
            )

            if quantity is None:

                return _error_result(
                    "quantity_required",
                    "Quantity must be a positive number.",
                )

            # ---------------------------------------------
            # Product ID supplied
            # ---------------------------------------------

            if product_id is not None:

                product_id = _safe_int(
                    product_id
                )

                if product_id is None:

                    return _error_result(
                        "product_invalid",
                        "The selected product has an invalid product ID.",
                    )

                product = (
                    db.query(Product)
                    .filter(
                        Product.id
                        == product_id
                    )
                    .first()
                )

                if product is None:

                    return _error_result(
                        "product_not_found",
                        f"Product {product_id} does not exist.",
                    )

            # ---------------------------------------------
            # Product name supplied
            # ---------------------------------------------

            else:

                product, candidates = (
                    _resolve_product(
                        db=db,
                        product_name=str(
                            product_name
                        ).strip(),
                    )
                )

                if product is None:

                    if candidates:

                        return _error_result(
                            "product_selection",
                            (
                                "Multiple products match "
                                f"'{product_name}'. "
                                "Please choose one."
                            ),
                            products=[
                                _serialize_product(
                                    candidate
                                )
                                for candidate in candidates
                            ],
                        )

                    return _error_result(
                        "product_not_found",
                        (
                            "No product found for "
                            f"'{product_name}'."
                        ),
                    )

                product_id = _safe_int(
                    _product_id(
                        product
                    )
                )

                if product_id is None:

                    return _error_result(
                        "product_invalid",
                        "The resolved product has no valid product ID.",
                    )

            # ---------------------------------------------
            # Re-read authoritative product
            # ---------------------------------------------

            authoritative_product = (
                db.query(Product)
                .filter(
                    Product.id
                    == product_id
                )
                .first()
            )

            if authoritative_product is None:

                return _error_result(
                    "product_not_found",
                    f"Product {product_id} does not exist.",
                )

            # ---------------------------------------------
            # Availability
            # ---------------------------------------------

            try:

                available = (
                    check_product_availability(
                        db=db,
                        product_id=product_id,
                        quantity=quantity,
                    )
                )

            except Exception as exc:

                print(
                    "[AVAILABILITY ERROR]",
                    type(exc).__name__,
                    str(exc),
                )

                return _error_result(
                    "availability_error",
                    str(exc),
                )

            if not available:

                display_name = (
                    _product_name(
                        authoritative_product
                    )
                    or str(
                        product_name
                        or product_id
                    )
                )

                return _error_result(
                    "product_unavailable",
                    (
                        f"'{display_name}' is not "
                        "available in the requested quantity."
                    ),
                    product=_serialize_product(
                        authoritative_product
                    ),
                    quantity=quantity,
                )

            resolved_items.append(
                {
                    "product_id": product_id,
                    "quantity": quantity,
                }
            )

            authoritative_products.append(
                authoritative_product
            )

        # -------------------------------------------------
        # Create order through backend
        # -------------------------------------------------

        print(
            "[CREATE ORDER]"
            f" user_id={user_id_int}"
            f" items={resolved_items}"
            f" address_id={address_id}"
            f" payment={payment_method}"
            f" checkout_id={checkout_id!r}"
        )

        try:

            order = create_order(
                db=db,
                user_id=user_id_int,
                address_id=address_id,
                items=resolved_items,
                payment_method=payment_method,
                checkout_id=checkout_id,
            )

        except ValueError as exc:

            print(
                "[CREATE ORDER VALUE ERROR]",
                str(exc),
            )

            return _error_result(
                "order_error",
                str(exc),
            )

        except Exception as exc:

            print(
                "[CREATE ORDER ERROR]",
                type(exc).__name__,
                str(exc),
            )

            return _error_result(
                "order_error",
                "I could not place the order because of a backend error.",
            )

        # -------------------------------------------------
        # Verify order ID
        # -------------------------------------------------

        order_id = getattr(
            order,
            "id",
            None,
        )

        order_id = _safe_int(
            order_id
        )

        if order_id is None:

            return _error_result(
                "order_error",
                "Order creation completed but no order ID was returned.",
            )

        # -------------------------------------------------
        # Obtain authoritative bill
        # -------------------------------------------------

        bill = getattr(
            order,
            "_buyqk_bill",
            None,
        )

        if bill is None:

            try:

                bill = build_order_bill(
                    db=db,
                    order=order,
                )

            except Exception as exc:

                print(
                    "[BILL GENERATION ERROR]",
                    type(exc).__name__,
                    str(exc),
                )

                return {
                    "tool_result": {
                        "success": False,
                        "type": "bill_error",
                        "error": (
                            "Order was created, but "
                            "the bill could not be generated."
                        ),
                        "order_id": order_id,
                    },
                    "order_id": order_id,
                    "checkout_id": checkout_id,
                    "checkout_status": "completed",
                    "order_created": True,
                }

        bill = _serialize_bill(
            bill
        )

        if bill is None:

            return {
                "tool_result": {
                    "success": False,
                    "type": "bill_error",
                    "error": (
                        "Order was created, but "
                        "the bill data is invalid."
                    ),
                    "order_id": order_id,
                    "checkout_id": checkout_id,
                    "checkout_status": "completed",
                    "order_created": True,
                },
                "order_id": order_id,
                "checkout_id": checkout_id,
                "checkout_status": "completed",
                "order_created": True,
            }

        # -------------------------------------------------
        # Preserve backend order ID
        # -------------------------------------------------

        bill["order_id"] = order_id

        billing_items = bill.get(
            "items"
        )

        subtotal = bill.get(
            "subtotal"
        )

        delivery_charge = bill.get(
            "delivery_charge"
        )

        discount = bill.get(
            "discount"
        )

        tax = bill.get(
            "tax"
        )

        total_amount = bill.get(
            "total"
        )

        currency = bill.get(
            "currency"
        )

        billing_payment_method = bill.get(
            "payment_method"
        )

        # -------------------------------------------------
        # Return authoritative transaction state
        # -------------------------------------------------

        updated_entities = dict(
            entities
        )

        if len(
            resolved_items
        ) == 1:

            updated_entities[
                "product_id"
            ] = resolved_items[0][
                "product_id"
            ]

            updated_entities[
                "quantity"
            ] = resolved_items[0][
                "quantity"
            ]

            if authoritative_products:

                updated_entities[
                    "product_name"
                ] = _product_name(
                    authoritative_products[0]
                )

        updated_entities[
            "address_id"
        ] = address_id

        updated_entities[
            "payment_method"
        ] = payment_method

        return {
            "tool_result": {
                "success": True,
                "type": "order_success",
                "order_id": order_id,
                "checkout_id": checkout_id,
                "checkout_status": "completed",
                "order_created": True,
                "status": getattr(
                    order,
                    "status",
                    None,
                ),
                "payment_status": getattr(
                    order,
                    "payment_status",
                    None,
                ),
                "payment_method": billing_payment_method,
                "total_amount": total_amount,
                "bill": bill,
                "purchase_summary": {
                    "items": billing_items,
                    "subtotal": subtotal,
                    "delivery_charge": delivery_charge,
                    "discount": discount,
                    "tax": tax,
                    "total": total_amount,
                    "currency": currency,
                    "payment_method": billing_payment_method,
                },
            },
            "entities": updated_entities,
            "checkout_id": checkout_id,
            "checkout_status": "completed",
            "order_created": True,
            "order_id": order_id,
            "product_id": (
                resolved_items[0][
                    "product_id"
                ]
                if len(
                    resolved_items
                ) == 1
                else state.get(
                    "product_id"
                )
            ),
            "quantity": (
                resolved_items[0][
                    "quantity"
                ]
                if len(
                    resolved_items
                ) == 1
                else state.get(
                    "quantity"
                )
            ),
            "address_id": address_id,
            "selected_address_id": address_id,
            "payment_method": payment_method,
            "selected_payment_method": payment_method,
            "billing": bill,
            "bill": bill,
            "billing_items": billing_items,
            "subtotal": subtotal,
            "delivery_charge": delivery_charge,
            "discount": discount,
            "tax": tax,
            "total_amount": total_amount,
            "currency": currency,
            "billing_payment_method": billing_payment_method,
            "awaiting_order_tracking_confirmation": True,
        }

    # =====================================================
    # TRACK ORDER
    # =====================================================

    if tool_name == "track_order":

        order_id = tool_args.get(
            "order_id"
        )

        if order_id is None:
            order_id = entities.get(
                "order_id"
            )

        if order_id is None:
            order_id = state.get(
                "order_id"
            )

        order_id = _safe_int(
            order_id
        )

        if order_id is None:

            return _error_result(
                "order_tracking",
                "Order ID is required.",
            )

        try:

            order = get_order(
                db=db,
                order_id=order_id,
            )

        except Exception as exc:

            print(
                "[TRACK ORDER ERROR]",
                type(exc).__name__,
                str(exc),
            )

            return _error_result(
                "order_tracking",
                str(exc),
            )

        if order is None:

            return _error_result(
                "order_tracking",
                f"Order {order_id} does not exist.",
            )

        # -------------------------------------------------
        # Authorization
        # -------------------------------------------------

        user_id_int = _safe_int(
            user_id
        )

        order_user_id = getattr(
            order,
            "user_id",
            None,
        )

        order_user_id = _safe_int(
            order_user_id
        )

        if (
            user_id_int is not None
            and order_user_id != user_id_int
        ):

            return _error_result(
                "order_tracking",
                "You are not authorized to view this order.",
            )

        # -------------------------------------------------
        # Authoritative bill
        # -------------------------------------------------

        try:

            bill = build_order_bill(
                db=db,
                order=order,
            )

        except Exception:

            bill = None

        serialized_bill = (
            _serialize_bill(
                bill
            )
            if bill
            else None
        )

        result: GraphState = {
            "tool_result": {
                "success": True,
                "type": "tracking",
                "order_id": getattr(
                    order,
                    "id",
                    order_id,
                ),
                "status": getattr(
                    order,
                    "status",
                    None,
                ),
                "payment_status": getattr(
                    order,
                    "payment_status",
                    None,
                ),
                "total_amount": getattr(
                    order,
                    "total_amount",
                    None,
                ),
                "bill": serialized_bill,
            },
            "order_id": getattr(
                order,
                "id",
                order_id,
            ),
            "awaiting_order_tracking_confirmation": False,
        }

        if serialized_bill is not None:

            result.update(
                {
                    "billing": serialized_bill,
                    "bill": serialized_bill,
                    "billing_items": serialized_bill.get(
                        "items",
                        [],
                    ),
                    "subtotal": serialized_bill.get(
                        "subtotal"
                    ),
                    "delivery_charge": serialized_bill.get(
                        "delivery_charge"
                    ),
                    "discount": serialized_bill.get(
                        "discount"
                    ),
                    "tax": serialized_bill.get(
                        "tax"
                    ),
                    "total_amount": serialized_bill.get(
                        "total"
                    ),
                    "currency": serialized_bill.get(
                        "currency"
                    ),
                    "billing_payment_method": serialized_bill.get(
                        "payment_method"
                    ),
                }
            )

        return result

    # =====================================================
    # CANCEL ORDER
    # =====================================================

    if tool_name == "cancel_order":

        user_id_int = _safe_int(
            user_id
        )

        if user_id_int is None:

            return _error_result(
                "order_cancel",
                "Valid user ID is required.",
            )

        order_id = tool_args.get(
            "order_id"
        )

        if order_id is None:
            order_id = entities.get(
                "order_id"
            )

        if order_id is None:
            order_id = state.get(
                "order_id"
            )

        order_id = _safe_int(
            order_id
        )

        if order_id is None:

            return _error_result(
                "order_cancel",
                "Order ID is required.",
            )

        try:

            order = cancel_order(
                db=db,
                order_id=order_id,
                user_id=user_id_int,
            )

            return {
                "tool_result": {
                    "success": True,
                    "type": "order_cancelled",
                    "order_id": getattr(
                        order,
                        "id",
                        order_id,
                    ),
                    "status": getattr(
                        order,
                        "status",
                        None,
                    ),
                },
                "entities": dict(
                    entities
                ),
                "order_id": order_id,
            }

        except ValueError as exc:

            return _error_result(
                "order_cancelled",
                str(exc),
            )

        except Exception as exc:

            print(
                "[CANCEL ORDER ERROR]",
                type(exc).__name__,
                str(exc),
            )

            return _error_result(
                "order_cancelled",
                str(exc),
            )

    # =====================================================
    # CREATE SUPPORT TICKET
    # =====================================================

    if tool_name == "create_support_ticket":

        user_id_int = _safe_int(
            user_id
        )

        if user_id_int is None:

            return _error_result(
                "support_ticket",
                "Valid user ID is required.",
            )

        order_id = tool_args.get(
            "order_id"
        )

        if order_id is None:
            order_id = entities.get(
                "order_id"
            )

        if order_id is None:
            order_id = state.get(
                "order_id"
            )

        order_id = _safe_int(
            order_id
        )

        message = tool_args.get(
            "message"
        )

        if message is None:
            message = tool_args.get(
                "description"
            )

        if message is None:
            message = state.get(
                "message",
                "",
            )

        if not _has_value(
            message
        ):

            return _error_result(
                "support_ticket",
                "Support message is required.",
            )

        try:

            ticket = create_ticket(
                db=db,
                user_id=user_id_int,
                subject="BuyQK Customer Support",
                description=str(
                    message
                ),
                order_id=order_id,
            )

            return {
                "tool_result": {
                    "success": True,
                    "type": "support_ticket",
                    "ticket_id": getattr(
                        ticket,
                        "id",
                        None,
                    ),
                    "status": getattr(
                        ticket,
                        "status",
                        None,
                    ),
                }
            }

        except ValueError as exc:

            return _error_result(
                "support_ticket",
                str(exc),
            )

        except Exception as exc:

            print(
                "[SUPPORT TICKET ERROR]",
                type(exc).__name__,
                str(exc),
            )

            return _error_result(
                "support_ticket",
                str(exc),
            )

    # =====================================================
    # Safety Fallback
    # =====================================================

    print(
        "[TOOL ERROR]"
        f" Unsupported tool: {tool_name}"
    )

    return _error_result(
        "unsupported_tool",
        f"Unsupported tool: {tool_name}",
    )