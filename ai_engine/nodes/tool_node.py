# =========================================================
# BuyQK AI - Tool Node
# =========================================================
#
# Phase 2
#
# Architecture:
#
#     User Message
#          ↓
#     Context Node
#          ↓
#     Entity Node
#          ↓
#     Planner Node
#          ↓
#     Policy Node
#          ↓
#     Decision Node
#          ↓
#     Tool Node
#          ↓
#     Backend Services
#          ↓
#     Tool Result
#          ↓
#     Response Node
#
# =========================================================
#
# RESPONSIBILITY
#
# This node EXECUTES an already-approved capability.
#
# It does NOT:
#
#   - understand natural language
#   - determine user intent
#   - decide what the user wants
#   - select the tool
#   - bypass policy
#   - calculate prices
#   - calculate tax
#   - calculate discounts
#   - calculate delivery charges
#   - calculate totals
#
# Planner:
#     decides WHAT should happen.
#
# Policy:
#     decides WHETHER the planned action is allowed.
#
# Decision:
#     routes the approved action.
#
# Tool Node:
#     EXECUTES the backend capability.
#
# Backend:
#     remains authoritative for business facts and mutations.
#
# =========================================================


