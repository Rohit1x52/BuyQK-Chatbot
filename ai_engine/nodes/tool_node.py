def _get_address_id(
    state: GraphState,
    args: dict[str, Any],
    entities: dict[str, Any],
) -> Any:
    """
    Resolve the selected address identifier.

    Priority:

        1. tool_args
        2. selected_address_id in GraphState
        3. address_id in GraphState
        4. entities

    The actual ownership check is performed against the
    backend database.
    """

    address_id = args.get(
        "address_id"
    )

    if address_id is not None:
        return address_id

    address_id = args.get(
        "selected_address_id"
    )

    if address_id is not None:
        return address_id

    address_id = state.get(
        "selected_address_id"
    )

    if address_id is not None:
        return address_id

    address_id = state.get(
        "address_id"
    )

    if address_id is not None:
        return address_id

    address_id = entities.get(
        "address_id"
    )

    if address_id is not None:
        return address_id

    return entities.get(
        "selected_address_id"
    )


def _validate_address(
    db: Session,
    user_id: int,
    address_id: Any,
) -> tuple[bool, str | None]:
    """
    Validate address existence and ownership.

    Backend data is authoritative.
    """

    address_id = _safe_int(
        address_id
    )

    if address_id is None:
        return (
            False,
            "Please select a valid delivery address.",
        )

    try:

        addresses = get_user_addresses(
            db=db,
            user_id=user_id,
        )

    except Exception as exc:

        print(
            "[ADDRESS VALIDATION ERROR]",
            type(exc).__name__,
            str(exc),
        )

        return (
            False,
            "Unable to validate the selected delivery address.",
        )

    for address in addresses:

        current_id = getattr(
            address,
            "id",
            None,
        )

        current_id = _safe_int(
            current_id
        )

        if current_id == address_id:
            return (
                True,
                None,
            )

    return (
        False,
        "The selected delivery address does not belong to this user.",
    )


