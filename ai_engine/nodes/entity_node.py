# Missing Fields
# =========================================================


def get_missing_fields(
    intent: str,
    entities: EntityOutput,
) -> list[str]:
    """
    Determine missing checkout fields.

    IMPORTANT:
    The order of this list is intentional.

    Product
      ↓
    Quantity
      ↓
    Address
      ↓
    Payment

    Response node should ask only the FIRST missing field.
    """

    missing: list[str] = []

    # =====================================================
    # Product Search
    # =====================================================

    if intent == "product_search":

        if not entities.product_name:
            missing.append(
                "product_name"
            )

    # =====================================================
    # Order Creation
    # =====================================================

    elif intent == "order_create":

        # Product
        if (
            entities.product_id is None
            and not entities.product_name
        ):

            missing.append(
                "product_name"
            )

        # Quantity
        elif (
            entities.quantity is None
            or entities.quantity <= 0
        ):

            missing.append(
                "quantity"
            )

        # Address
        elif entities.address_action == "add":
            for field_name, field_value in (
                ("address_label", entities.address_label),
                ("address_text", entities.address_text),
                ("address_city", entities.address_city),
                ("address_state", entities.address_state),
                ("address_postal_code", entities.address_postal_code),
            ):
                if not field_value:
                    missing.append(field_name)

        elif entities.address_id is None:

            missing.append(
                "address_selection"
            )

        # Payment
        elif not entities.payment_method:

            missing.append(
                "payment_method"
            )

    # =====================================================
    # Cart
    # =====================================================

    elif intent == "cart":
        action = entities.cart_action
        if action in {"add_item", "remove_item", "update_quantity"}:
            if entities.product_id is None and not entities.product_name:
                missing.append("product_reference")
            elif action in {"add_item", "update_quantity"} and (
                entities.quantity is None or entities.quantity <= 0
            ):
                missing.append("quantity")
        elif action is None:
            missing.append("cart_action")

    # =====================================================
    # Tracking
    # =====================================================

    elif intent == "order_tracking":

        if (
            entities.order_id is None
            and not entities.order_reference_type
            and not entities.order_reference
        ):

            missing.append(
                "order_id"
            )

    # =====================================================
    # Cancellation
    # =====================================================

    elif intent == "order_cancel":

        if (
            entities.order_id is None
            and not entities.order_reference_type
            and not entities.order_reference
        ):
            missing.append("order_id")

    return missing


