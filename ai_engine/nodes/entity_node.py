class LLMEntityOutput(BaseModel):
    """
    Fields the LLM is allowed to extract.

    IMPORTANT: product_id is deliberately absent. Product IDs are
    database identifiers and must never be hallucinated by the LLM.

    IMPORTANT (cart_action): this field is intentionally a plain
    Optional[str], NOT an Optional[Literal[...]] enum.

    When declared as a strict Literal, the JSON schema sent to the
    provider for structured/tool-call output requires the value to be
    either one of the enum members or JSON null. The underlying model
    was observed emitting the literal TEXT "None" for an empty value
    (a text-based tool-call format artifact) instead of real null.
    That text matches neither the enum nor null, so the provider's
    own server-side schema validation rejected the entire tool call
    with a 400 ("tool call validation failed") -- before this code
    ever ran, so the _clean_none_strings validator below never got a
    chance to fix it.

    Keeping this field as a permissive Optional[str] lets that
    provider-side check pass (any string, including "None", is a
    valid string), after which _clean_none_strings converts the text
    "None"/"null"/"" to real None client-side, and entity_node()
    separately validates the cleaned value against the actual allowed
    cart action set before it is trusted anywhere downstream.
    """

    items: Optional[list[dict[str, Any]]] = Field(
        default=None,
        description=(
            "Normalized product/quantity tuples in a single multi-item order."
        ),
    )

    product_name: Optional[str] = Field(
        default=None,
        description="Product name mentioned or implied by the user.",
    )

    quantity: int | str | None = Field(
        default=None,
        description="Quantity supplied by the user. Accept an integer, numeric string, or null. Never invent a quantity.",
    )

    order_id: int | str | None = Field(
        default=None,
        description="Order ID supplied by the user. Accept an integer, numeric string, or null. Never invent an order ID.",
    )

    order_reference: Optional[str] = Field(
        default=None,
        description="Explicit order reference supplied by the user, or null. Never invent.",
    )

    order_reference_type: Optional[str] = Field(
        default=None,
        description="Order reference kind when explicit: specific, latest, or previous.",
    )

    cancellation_reason: Optional[str] = Field(
        default=None,
        description="Natural-language cancellation reason explicitly supplied by the user, or null. Never invent.",
    )

    address_id: int | str | None = Field(
        default=None,
        description="Saved address ID supplied by the user. Accept an integer, numeric string, or null. Never invent an address ID.",
    )

    address_text: Optional[str] = Field(
        default=None,
        description="Natural-language delivery address supplied by the user.",
    )
    address_action: Optional[str] = Field(default=None)
    address_label: Optional[str] = Field(default=None)
    address_line_2: Optional[str] = Field(default=None)
    address_city: Optional[str] = Field(default=None)
    address_state: Optional[str] = Field(default=None)
    address_postal_code: Optional[str] = Field(default=None)

    payment_method: Optional[str] = Field(
        default=None,
        description="Payment method: upi or cod.",
    )

    delivery_preference: Optional[str] = Field(
        default=None,
        description=(
            "Explicit user delivery preference in natural language, or null. "
            "Do not invent a delivery option or availability."
        ),
    )

    cart_action: Optional[str] = Field(
        default=None,
        description=(
            "Cart operation requested by the user: one of add_item, "
            "remove_item, update_quantity, clear_cart, show_cart, "
            "checkout. Return null for non-cart messages."
        ),
    )

    @model_validator(mode="before")
    @classmethod
    def _clean_none_strings(cls, data: Any) -> Any:
        """
        Some providers emit the literal text "None"/"null"/"" for a
        field that should be empty, instead of real JSON null. Clean
        that up before pydantic validates individual fields.
        """
        if isinstance(data, dict):
            for k, v in data.items():
                if isinstance(v, str) and v.strip().lower() in ("none", "null", ""):
                    data[k] = None
        return data


class _LLMProviderEntityOutput(BaseModel):
    """Provider-facing entity schema.

    Keep this schema deliberately simple for provider/tool calling.

    IMPORTANT:
    - product_id is intentionally absent.
    - cart_action is intentionally absent.
    - Numeric transactional values are represented as strings at the
      provider boundary and normalized locally afterwards.
    - Avoid unions such as ``int | str | None`` here because some
      providers/models emit malformed tool arguments when the generated
      JSON schema contains ``anyOf`` branches.
    """

    product_name: Optional[str] = Field(
        default=None,
        description="Product name explicitly mentioned by the user, or null.",
    )
    quantity: Optional[int] = Field(
        default=None,
        description="Explicit quantity as digits, or null. Never invent.",
    )
    order_id: Optional[int] = Field(
        default=None,
        description="Explicit order ID as digits, or null. Never invent.",
    )
    order_reference: Optional[str] = Field(
        default=None,
        description="Explicit order reference supplied by the user, or null. Never invent.",
    )
    order_reference_type: Optional[str] = Field(
        default=None,
        description="Order reference kind: specific, latest, or previous, or null.",
    )
    cancellation_reason: Optional[str] = Field(
        default=None,
        description="Explicit natural-language cancellation reason, or null. Never invent.",
    )
    address_id: Optional[int] = Field(
        default=None,
        description="Explicit saved address ID as digits, or null. Never invent.",
    )
    address_text: Optional[str] = Field(
        default=None,
        description="Explicit natural-language delivery address, or null.",
    )
    address_action: Optional[str] = Field(default=None)
    address_label: Optional[str] = Field(default=None)
    address_line_2: Optional[str] = Field(default=None)
    address_city: Optional[str] = Field(default=None)
    address_state: Optional[str] = Field(default=None)
    address_postal_code: Optional[str] = Field(default=None)
    payment_method: Optional[str] = Field(
        default=None,
        description="Payment method such as upi or cod, or null.",
    )
    delivery_preference: Optional[str] = Field(
        default=None,
        description=(
            "Explicit natural-language delivery preference from the user, or null. "
            "Never invent a delivery option or availability."
        ),
    )

    @model_validator(mode="before")
    @classmethod
    def _clean_provider_values(cls, data: Any) -> Any:
        """Normalize provider artifacts before local validation."""
        if not isinstance(data, dict):
            return data

        cleaned = dict(data)

        for key, value in cleaned.items():
            if isinstance(value, str):
                normalized = value.strip()
                if normalized.lower() in {"none", "null", ""}:
                    cleaned[key] = None
                else:
                    cleaned[key] = normalized

        return cleaned


