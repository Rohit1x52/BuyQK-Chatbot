# =========================================================
# Product Fallback
# =========================================================


def detect_product_fallback(
    message: str,
    conversation_history: list[dict[str, Any]] | None,
) -> Optional[str]:
    """
    Conservative product-name fallback for short checkout turns.

    This function does NOT resolve a product ID and does not query
    the database. It only tries to recover a product name from an
    earlier user order/buy request when the LLM did not return one.
    """

    # If the current message is a quantity/address/payment continuation,
    # recover the product from an earlier user order statement.
    user_messages = get_user_history(
        conversation_history
    )

    if not user_messages:
        return None

    # Do not treat a current explicit product-like request as a fallback
    # when it is actually just a quantity/payment/address continuation.
    continuation_only = (
        detect_quantity(message) is not None
        or detect_payment_method(message) is not None
        or detect_address_id(message) is not None
        or bool(detect_address_text(message))
        or bool(re.fullmatch(
            r"\s*(?:home|work|office|selected(?:\s+delivery)?\s+address|use\s+(?:the\s+)?selected\s+address)\s*",
            message or "",
            flags=re.IGNORECASE,
        ))
    )

    if not continuation_only:
        return None

    patterns = (
        r"\bi\s+(?:want|need)\s+to\s+(?:order|buy|get)\s+(.+?)\s*$",
        r"\bi\s+(?:want|need)\s+(?:to\s+)?(?:order|buy|get)\s+(.+?)\s*$",
        r"\bi(?:'d|\s+would)\s+like\s+to\s+(?:order|buy|get)\s+(.+?)\s*$",
        r"\b(?:order|buy|get|purchase)\s+(.+?)\s*$",
    )

    for _, content in reversed(user_messages):
        if detect_quantity(content, allow_plain_number=False) is not None:
            # A quantity-only message is not a product statement.
            continue

        for pattern in patterns:
            match = re.search(
                pattern,
                content,
                flags=re.IGNORECASE,
            )

            if not match:
                continue

            candidate = (
                match.group(1)
                .strip()
                .rstrip(".!?,")
            )

            if not candidate:
                continue

            if detect_quantity(candidate) is not None:
                continue

            if detect_payment_method(candidate) is not None:
                continue

            return candidate

    return None


# =========================================================
# New Order Detection
# =========================================================


def _is_new_order_request(
    message: str,
) -> bool:
    """
    Detect an explicit request to start a new order.

    This prevents stale checkout information from an
    earlier completed order being reused.
    """

    if not message:
        return False

    text = (
        message
        .strip()
        .lower()
    )

    continuation_phrases = (
        "actually",
        "instead",
        "change it",
        "make it",
        "change the product",
    )

    if any(
        phrase in text
        for phrase in continuation_phrases
    ):
        return False

    new_order_patterns = (
        r"\bi\s+want\s+to\s+order\b",
        r"\bi'd\s+like\s+to\s+order\b",
        r"\bi\s+would\s+like\s+to\s+order\b",
        r"\bi\s+want\s+to\s+buy\b",
        r"\bi'd\s+like\s+to\s+buy\b",
        r"\bplace\s+(?:an\s+)?order\b",
        r"\bnew\s+order\b",
    )

    return any(
        re.search(
            pattern,
            text,
            flags=re.IGNORECASE,
        )
        for pattern in new_order_patterns
    )


