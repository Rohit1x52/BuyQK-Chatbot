# =========================================================
# LLM ENTITY OUTPUT
# =========================================================


class LLMEntityOutput(BaseModel):
    """
    Structured understanding of the CURRENT user message.

    This model intentionally contains user-understandable
    information only.

    Database identifiers must never be hallucinated.
    """

    product_name: Optional[str] = Field(
        default=None,
        description=(
            "The product the user is referring to. "
            "Understand the meaning semantically."
        ),
    )

    quantity: Optional[int] = Field(
        default=None,
        ge=1,
        description=(
            "Explicit quantity understood from the "
            "current user message."
        ),
    )

    order_id: Optional[int] = Field(
        default=None,
        ge=1,
        description=(
            "Order ID explicitly referred to by the user."
        ),
    )

    address_id: Optional[int] = Field(
        default=None,
        ge=1,
        description=(
            "Saved address ID explicitly selected by "
            "the user."
        ),
    )

    address_text: Optional[str] = Field(
        default=None,
        description=(
            "Natural-language address or delivery location "
            "understood from the message."
        ),
    )

    payment_method: Optional[str] = Field(
        default=None,
        description=(
            "Payment method understood from the current "
            "message. Do not invent unavailable methods."
        ),
    )


# =========================================================
# CURRENT-TURN INTENT
# =========================================================


class IntentDecision(BaseModel):
    """
    Understand what the user means NOW.

    IMPORTANT:

    This is understanding, not execution planning.

    The planner node decides what action/tool should happen
    after this understanding has been produced.
    """

    intent: Literal[
        "product_search",
        "order_create",
        "order_tracking",
        "order_cancel",
        "customer_support",
        "general",
    ]

    confidence: float = Field(
        default=1.0,
        ge=0.0,
        le=1.0,
    )


