class IntentDecision(BaseModel):
    """
    AI decision for the CURRENT user turn.

    Previous intent/entity state is context only. It must never
    override the intent of the current message.
    """

    intent: Literal[
        "product_search",
        "order_create",
        "order_tracking",
        "order_cancel",
        "customer_support",
        "cart",
        "general",
    ] = Field(
        description=(
            "The user's intent for the current message only."
        )
    )

    order_action: Literal[
        "start_new_order",
        "continue_order",
        "none",
    ] = Field(
        description=(
            "For order-related messages, decide whether the "
            "user is starting a new order or continuing an "
            "existing checkout. Use none for non-order turns."
        )
    )

    # NOTE: kept as a plain Optional[str] rather than a strict Literal
    # enum for the same reason as LLMEntityOutput.cart_action above --
    # a strict-enum schema can be rejected server-side if the model
    # emits literal text like "None" instead of a real null/default.
    # Any value outside the known set is treated as "none" wherever
    # this field is consumed.
    cart_action: Optional[str] = Field(
        default="none",
        description=(
            "Cart operation for the current message: one of add_item, "
            "remove_item, update_quantity, clear_cart, show_cart, "
            "checkout, or 'none' when this is not a cart turn."
        ),
    )

    confidence: float = Field(
        default=1.0,
        ge=0.0,
        le=1.0,
        description="Confidence in the current-turn intent decision.",
    )

    @model_validator(mode="before")
    @classmethod
    def _clean_none_strings(cls, data: Any) -> Any:
        if isinstance(data, dict):
            for k, v in data.items():
                if k == "order_action" and isinstance(v, str) and v.strip().lower() == "none":
                    continue
                if isinstance(v, str) and v.strip().lower() in ("none", "null", ""):
                    data[k] = None
        return data




