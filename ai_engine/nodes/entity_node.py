def _has_value(
    value: Any,
) -> bool:
    if value is None:
        return False

    if isinstance(value, str):
        return bool(value.strip())

    return True


def _normalize_text(
    value: Any,
) -> Optional[str]:

    if value is None:
        return None

    text = str(value).strip()

    return text if text else None


# =========================================================
# Quantity Detection
# =========================================================


def detect_quantity(
    message: str,
    allow_plain_number: bool = True,
) -> Optional[int]:
    """
    Detect explicit quantity from a message.

    Examples:

        3 packets
        2 kg
        quantity 4
        qty = 5
        make it 6
        change it to 7
        want 3

    Plain numbers are supported for direct user replies:

        3
        5
    """

    if not message:
        return None

    patterns = [
        # 3 packets
        r"\b(\d+)\s*(?:packets?|packs?|pieces?|pcs?|items?|units?)\b",

        # 3 kg / 3 kilograms
        r"\b(\d+)\s*(?:kg|kgs|kilograms?|l|litres?|liters?)\b",

        # 3 grams
        r"\b(\d+)\s*(?:g|grams?)\b",

        # quantity 3
        r"\b(?:quantity|qty)\s*(?:is|=|:)?\s*(\d+)\b",

        # make it 5
        r"\bmake\s+it\s+(\d+)\b",

        # change it to 5
        r"\bchange\s+(?:it\s+)?to\s+(\d+)\b",

        # want 3
        r"\b(?:want|need|like)\s+(\d+)\b",

        # order 3 maggi / buy 5 milk (number between verb and product)
        r"\b(?:order|buy|get|purchase|add)\s+(\d+)\s+[a-zA-Z]",
    ]

    if allow_plain_number:
        patterns.append(
            r"^\s*(\d+)\s*$"
        )

    for pattern in patterns:

        match = re.search(
            pattern,
            message,
            flags=re.IGNORECASE,
        )

        if not match:
            continue

        try:

            value = int(
                match.group(1)
            )

            if value > 0:
                return value

        except (
            TypeError,
            ValueError,
        ):
            continue

    return None


# =========================================================
# Recover Quantity From Previous User Turns
# =========================================================


def recover_quantity_from_history(
    conversation_history: list[dict[str, Any]] | None,
) -> Optional[int]:
    """
    Recover the latest quantity supplied by the USER.

    This fixes the main bug:

        User: I want Amul milk
        Assistant: How much?
        User: 3 packets
        Assistant: Choose address
        User: Use selected address

    On the final turn, the current message contains no
    quantity. Therefore quantity must be recovered from
    the earlier user turn.
    """

    user_messages = get_user_history(
        conversation_history
    )

    if not user_messages:
        return None

    # -----------------------------------------------------
    # First pass:
    # Strong quantity expressions.
    # -----------------------------------------------------

    for _, content in reversed(
        user_messages
    ):

        value = detect_quantity(
            content,
            allow_plain_number=False,
        )

        if value is not None:
            return value

    # -----------------------------------------------------
    # Second pass:
    # A plain numeric answer is valid when the assistant
    # immediately before it asked for quantity.
    # -----------------------------------------------------

    for index, content in reversed(
        user_messages
    ):

        if not re.fullmatch(
            r"\s*\d+\s*",
            content,
        ):
            continue

        assistant_message = (
            get_previous_assistant_message(
                conversation_history,
                index,
            )
            .lower()
        )

        quantity_question = any(
            phrase in assistant_message
            for phrase in (
                "how much",
                "how many",
                "quantity",
                "how many packets",
                "how many pieces",
                "how many items",
                "what quantity",
            )
        )

        if not quantity_question:
            continue

        value = detect_quantity(
            content,
            allow_plain_number=True,
        )

        if value is not None:
            return value

    return None


# =========================================================
# Address Text Detection
# =========================================================


def detect_address_text(
    message: str,
) -> Optional[str]:

    if not message:
        return None

    patterns = [
        r"(?:my\s+)?(?:delivery\s+)?address\s+(?:is|:)\s*(.+)",

        r"(?:deliver|delivery)\s+(?:it\s+)?to\s+(.+)",

        r"(?:send|ship)\s+(?:it\s+)?to\s+(.+)",
    ]

    for pattern in patterns:

        match = re.search(
            pattern,
            message,
            flags=re.IGNORECASE,
        )

        if not match:
            continue

        value = (
            match.group(1)
            .strip()
            .rstrip(".")
        )

        if value:
            return value

    return None


# =========================================================
# Address ID Detection
# =========================================================


def detect_address_id(
    message: str,
) -> Optional[int]:

    if not message:
        return None

    match = re.search(
        r"\baddress\s*(?:id)?\s*[:#]?\s*(\d+)\b",
        message,
        flags=re.IGNORECASE,
    )

    if not match:
        return None

    try:

        value = int(
            match.group(1)
        )

        return (
            value
            if value > 0
            else None
        )

    except ValueError:

        return None


# =========================================================
# Order ID Detection
# =========================================================


def detect_order_id(
    message: str,
) -> Optional[int]:

    if not message:
        return None

    # Require an explicit ID/number/no/# qualifier so that
    # "I want to order 11 Maggi" is NOT misread as order_id=11.
    match = re.search(
        r"\border\s+(?:id|number|no\.?)\s*[:#]?\s*(\d+)\b",
        message,
        flags=re.IGNORECASE,
    )

    if not match:
        # Also accept "order #123" (hash directly after order)
        match = re.search(
            r"\border\s*[#]\s*(\d+)\b",
            message,
            flags=re.IGNORECASE,
        )

    if not match:
        # Tracking-specific forms such as "Track order 123" and
        # "Track my order 123" are safe because the tracking verb
        # disambiguates the number from a purchase quantity.
        match = re.search(
            r"\btrack(?:ing)?\s+(?:my\s+)?order\s*[#:]?\s*(\d+)\b",
            message,
            flags=re.IGNORECASE,
        )

    if not match:
        # Cancellation-specific forms such as:
        # "Cancel order 123"
        # "Cancel my order 123"
        # "Cancel order #123"
        #
        # The cancellation verb disambiguates the number from an
        # ordinary purchase quantity such as "order 11 Maggi".
        match = re.search(
            r"\bcancel(?:ling)?\s+(?:my\s+)?order\s*[#:]?\s*(\d+)\b",
            message,
            flags=re.IGNORECASE,
        )

    if not match:
        # "Order 123 status?" / "Order 123 tracking". Require a
        # tracking/status qualifier so ordinary purchase quantities
        # such as "order 11 Maggi" are not misclassified.
        match = re.search(
            r"\border\s+(\d+)\s+(?:status|tracking|track|location|progress|update|delivery)\b",
            message,
            flags=re.IGNORECASE,
        )

    if not match:
        return None

    try:

        value = int(
            match.group(1)
        )

        return (
            value
            if value > 0
            else None
        )

    except ValueError:

        return None


# =========================================================
# Order Reference Detection
# =========================================================


def detect_order_reference_type(message: str) -> Optional[str]:
    """Detect whether the user means a specific, latest, or previous order."""
    if not message:
        return None

    text = re.sub(r"\s+", " ", message.strip()).casefold()

    if re.search(r"\b(?:latest|most recent|last)\s+(?:my\s+)?order\b", text):
        return "latest"

    if re.search(r"\b(?:previous|prior|earlier|pichla|pichhli|pichle)\s+(?:my\s+)?order\b", text):
        return "previous"

    return None


def detect_order_reference(message: str) -> Optional[str]:
    """Extract an explicit non-numeric order reference such as BQK... without inventing it."""
    if not message:
        return None

    match = re.search(r"\bBQK[-_A-Za-z0-9]+\b", message, flags=re.IGNORECASE)
    if not match:
        return None

    return match.group(0).strip()


# =========================================================
# Cancellation Reason Detection
# =========================================================


def detect_cancellation_reason(message: str) -> Optional[str]:
    """Extract only an explicitly supplied cancellation reason."""
    if not message:
        return None

    text = re.sub(r"\s+", " ", message.strip()).strip()
    if not text:
        return None

    patterns = (
        r"\b(?:because|reason is|reason:)\s+(.+)$",
        r"\b(?:cancel(?:ling|lation)?\s+reason)\s*[:=-]\s*(.+)$",
    )
    for pattern in patterns:
        match = re.search(pattern, text, flags=re.IGNORECASE)
        if match:
            reason = match.group(1).strip(" \t.,;:-")
            if reason:
                return reason
    return None


# =========================================================
# Delivery Preference Detection
# =========================================================


def detect_delivery_preference(
    message: str,
) -> Optional[str]:
    """
    Detect an explicit user delivery preference without mapping it to
    a backend delivery option or claiming availability.

    This intentionally captures the user's natural-language preference
    rather than maintaining a delivery catalog.
    """

    if not message:
        return None

    text = message.strip()

    patterns = [
        # Explicit preference labels.
        r"\b(?:delivery\s+)?preference\s*[:=]\s*(.+)",
        r"\b(?:delivery|deliver)\s+(?:preference|speed|timing)\s*[:=]\s*(.+)",

        # Natural-language delivery preference.
        r"\b(?:i\s+)?(?:want|need|prefer)\s+(.+?)\s+delivery\b",
        r"\b(?:mujhe|mujhko)\s+(.+?)\s+delivery\s+(?:chahiye|chaahiye)\b",
        r"\b(.+?)\s+delivery\s+(?:chahiye|chaahiye)\b",
        r"\b(.+?)\s+delivery\b",
    ]

    for pattern in patterns:
        match = re.search(
            pattern,
            text,
            flags=re.IGNORECASE,
        )
        if not match:
            continue

        value = match.group(1).strip().rstrip(".,!?")
        if value:
            return value

    return None


# =========================================================
# Payment Detection
# =========================================================


def detect_payment_method(
    message: str,
) -> Optional[str]:

    if not message:
        return None

    text = (
        message
        .strip()
        .lower()
    )

    # UPI
    if re.search(
        r"\bupi\b",
        text,
    ):
        return "upi"

    # COD
    if (
        "cash on delivery" in text
        or re.search(
            r"\bcod\b",
            text,
        )
    ):
        return "cod"

    return None


