# LLM Entity Extraction
# =========================================================


def _build_entity_messages(
    message: str,
    conversation_history: list[dict[str, Any]] | None,
    include_history: bool = True,
) -> list[Any]:
    """Build a compact, provider-safe extraction prompt."""
    clean_message = (message or "").strip()

    history_text = (
        format_conversation_history(conversation_history)
        if include_history
        else "No previous conversation."
    )

    return [
        SystemMessage(content=ENTITY_SYSTEM_PROMPT),
        HumanMessage(
            content=(
                "RECENT CONVERSATION:\n"
                "--------------------\n"
                f"{history_text}\n\n"
                "CURRENT USER MESSAGE:\n"
                "--------------------\n"
                f"{clean_message}\n\n"
                "Return only the structured entity fields allowed by "
                "your schema. Preserve known values from the conversation "
                "when they are clearly part of the same transaction. "
                "Never invent missing values."
            )
        ),
    ]


def _safe_llm_entity_result(
    result: Any,
) -> LLMEntityOutput:
    """Convert a provider result into our internal entity model safely."""
    if isinstance(result, LLMEntityOutput):
        return result

    if not isinstance(result, _LLMProviderEntityOutput):
        return LLMEntityOutput()

    return LLMEntityOutput(
        product_name=_normalize_text(result.product_name),
        quantity=result.quantity,
        order_id=result.order_id,
        order_reference=result.order_reference,
        order_reference_type=result.order_reference_type,
        address_id=result.address_id,
        address_text=(result.address_text.strip() if result.address_text else None),
        address_action=(result.address_action.strip().lower() if result.address_action else None),
        address_label=(result.address_label.strip() if result.address_label else None),
        address_line_2=(result.address_line_2.strip() if result.address_line_2 else None),
        address_city=(result.address_city.strip() if result.address_city else None),
        address_state=(result.address_state.strip() if result.address_state else None),
        address_postal_code=(result.address_postal_code.strip() if result.address_postal_code else None),
        payment_method=_normalize_text(result.payment_method),
        cart_action=None,
    )


def extract_entities(
    message: str,
    conversation_history: list[dict[str, Any]] | None = None,
) -> LLMEntityOutput:
    """
    LLM-first entity extraction with a bounded provider retry.

    The LLM remains the primary semantic extractor. If the provider rejects
    the structured tool call, the second attempt uses a smaller prompt
    without history. If both attempts fail, an empty result is returned and
    entity_node() performs deterministic extraction/recovery.

    product_id is never accepted from the LLM.
    """
    if not message or not message.strip():
        return LLMEntityOutput()

    attempts = (
        _build_entity_messages(
            message=message,
            conversation_history=conversation_history,
            include_history=True,
        ),
        _build_entity_messages(
            message=message,
            conversation_history=None,
            include_history=False,
        ),
    )

    last_error: Exception | None = None

    for attempt_number, messages in enumerate(attempts, start=1):
        try:
            result = structured_llm.invoke(messages)
            return _safe_llm_entity_result(result)

        except Exception as exc:
            last_error = exc
            print(
                "[ENTITY LLM FALLBACK]"
                f" attempt={attempt_number}/2 "
                f"{type(exc).__name__}: {exc}"
            )

    if last_error is not None:
        print(
            "[ENTITY LLM FALLBACK]"
            " deterministic recovery will be used"
        )

    return LLMEntityOutput()


# =========================================================
# Entity Node
# =========================================================


def entity_node(
    state: GraphState,
) -> GraphState:
    """
    Main BuyQK entity-resolution node.

    This is intentionally deterministic around checkout
    state.

    Critical example:

        User:
            I want to order Amul milk

        Assistant:
            How much Amul milk would you like?

        User:
            3 packets

        Assistant:
            Please choose your delivery address.

        User:
            Use the selected delivery address.

    Final state MUST contain:

        product_name = Amul milk
        quantity = 3
        address_id = selected address

    and NOT ask for quantity again.
    """

    message = (
        state.get(
            "message",
            "",
        )
        or ""
    ).strip()

    original_intent = state.get(
        "intent",
        "general",
    )

    conversation_history = (
        state.get(
            "conversation_history",
            [],
        )
        or []
    )

    existing_entities = dict(
        state.get(
            "entities",
            {},
        )
        or {}
    )

    # =====================================================
    # Preserve persisted delivery preference
    # =====================================================
    #
    # delivery_preference is a top-level GraphState field and is
    # persisted by the graph runner. Restore it into entity state
    # only when the entity snapshot does not already contain it.
    #
    # This is user preference state only. It is never treated as
    # a backend delivery option or availability result.
    # =====================================================

    persisted_delivery_preference = _normalize_text(
        state.get("delivery_preference")
    )

    if (
        persisted_delivery_preference
        and not existing_entities.get("delivery_preference")
    ):
        existing_entities["delivery_preference"] = (
            persisted_delivery_preference
        )

    # =====================================================
    # CURRENT-TURN AI INTENT
    # =====================================================
    #
    # This is the most important distinction in the workflow:
    #
    #     entity state = what we know
    #     current intent = what the user wants NOW
    #
    # A previous order_create intent must never automatically
    # become the intent of the next user message.
    # =====================================================

    # Deterministic order-reference extraction is available before current-turn
    # intent finalization so a bare numeric reply can continue a tracking prompt.
    explicit_order_id = detect_order_id(message)
    if (
        explicit_order_id is None
        and bool(state.get("awaiting_order_tracking_order_id"))
        and re.fullmatch(r"\s*\d+\s*", message)
    ):
        explicit_order_id = int(message.strip())

    # intent_node already classified the CURRENT turn. Trust it for
    # cart and all non-order turns. Re-running a second classifier here
    # was the source of the cart Literal validation failure.
    if str(original_intent or "general").strip().lower() != "order_create":
        resolved_current_intent = str(original_intent or "general").strip().lower()
        if resolved_current_intent not in {
            "product_search", "order_tracking", "order_cancel",
            "customer_support", "cart", "general",
        }:
            resolved_current_intent = "general"
        intent_decision = IntentDecision(
            intent=resolved_current_intent,
            order_action="none",
            cart_action="none",
            confidence=1.0,
        )
    else:
        intent_decision = resolve_current_turn_intent(
            state=state,
            message=message,
        )
        resolved_current_intent = intent_decision.intent

    # A follow-up containing the requested order ID continues the
    # tracking task even if the generic intent classifier labels the
    # bare number as general.
    if (
        bool(state.get("awaiting_order_tracking_order_id"))
        and explicit_order_id is not None
        and resolved_current_intent == "general"
    ):
        resolved_current_intent = "order_tracking"
        intent_decision = IntentDecision(
            intent="order_tracking",
            order_action="none",
            cart_action="none",
            confidence=1.0,
        )

    new_order = (
        resolved_current_intent
        == "order_create"
        and intent_decision.order_action
        == "start_new_order"
    )

    # History recovery is allowed only when the AI says the
    # CURRENT turn is an order continuation.
    previous_checkout_id = (
        state.get("checkout_id")
        or _recover_checkout_id_from_history(
            conversation_history
        )
    )

    if new_order:
        checkout_id = str(uuid.uuid4())
        checkout_status = "collecting"
        order_created = False
    elif resolved_current_intent == "order_create":
        checkout_id = (
            str(previous_checkout_id).strip()
            if previous_checkout_id
            else _ensure_checkout_id(
                state,
                conversation_history,
            )
        )
        checkout_status = state.get("checkout_status") or "collecting"
        order_created = bool(state.get("order_created", False))
    else:
        checkout_id = previous_checkout_id
        checkout_status = state.get("checkout_status")
        order_created = bool(state.get("order_created", False))

    checkout_context = (
        resolved_current_intent == "order_create"
        and not new_order
    )

    if new_order:

        # Clear every order-specific value.
        # The new message will establish the new product.
        existing_entities.pop(
            "product_id",
            None,
        )

        existing_entities.pop(
            "product_name",
            None,
        )

        existing_entities.pop(
            "quantity",
            None,
        )

        existing_entities.pop(
            "address_id",
            None,
        )

        existing_entities.pop(
            "address_text",
            None,
        )

        for _address_field in (
            "address_action",
            "address_label",
            "address_line_2",
            "address_city",
            "address_state",
            "address_postal_code",
        ):
            existing_entities.pop(
                _address_field,
                None,
            )

        existing_entities.pop(
            "payment_method",
            None,
        )

        existing_entities.pop(
            "delivery_preference",
            None,
        )

        existing_entities.pop(
            "order_id",
            None,
        )

        existing_entities.pop("cancellation_reason", None)

    # =====================================================
    # Deterministic cart-action detection
    # =====================================================
    #
    # FIX: previously the deterministic-turn shortcut below checked
    # detect_quantity()/detect_product_from_message()/etc. with NO
    # guard for cart intent. A message such as:
    #
    #     "Add 3 Tata Tea Gold and 2 Surf Excel Matic in cart"
    #
    # matched the quantity pattern ("add 3 <word>"), which made
    # deterministic_turn True and skipped the LLM entity-extraction
    # call entirely -- so cart_action was never resolved by anything,
    # leaving entities = {"quantity": 3} and missing_fields =
    # ["cart_action"] even though the message obviously requested an
    # add_item cart operation.
    #
    # Resolve cart_action deterministically first. For clear/show/
    # checkout, no product information is needed, so the LLM call can
    # still be safely skipped. For add/remove/update, product/quantity
    # details still require the LLM extraction call.
    # =====================================================

    cart_action_resolved_deterministically = False

    if resolved_current_intent == "cart":

        detected_cart_action = detect_cart_action_from_message(
            message
        )

        if detected_cart_action:

            existing_entities["cart_action"] = detected_cart_action

            if detected_cart_action in {
                "clear_cart",
                "show_cart",
                "checkout",
            }:
                cart_action_resolved_deterministically = True

    # =====================================================
    # LLM extraction
    # =====================================================
    # Product/order messages still go through the LLM FIRST.
    # Deterministic extraction below is the safety net and normalization
    # layer, not a catalog-specific replacement for the LLM.
    deterministic_turn = (
        resolved_current_intent != "cart"
        and _is_continuation_only_message(message)
    ) or (
        resolved_current_intent == "cart"
        and cart_action_resolved_deterministically
    )

    extracted = (
        LLMEntityOutput()
        if deterministic_turn
        else extract_entities(
            message=message,
            conversation_history=conversation_history,
        )
    )


    extracted_entities = (
        extracted.model_dump(
            exclude_none=True
        )
    )

    # =====================================================
    # Merge existing graph state
    # =====================================================

    entities = dict(
        existing_entities
    )

    for key, value in extracted_entities.items():

        if value is not None:

            entities[key] = value

    # =====================================================
    # IMPORTANT PRODUCT-ID RULE
    # =====================================================
    #
    # product_id is backend authoritative. The LLM model does not
    # contain this field, so it cannot overwrite it here.
    # Preserve an existing backend-resolved ID until the user
    # explicitly changes the product.
    #
    previous_product_name = existing_entities.get(
        "product_name"
    )
    existing_product_id = existing_entities.get(
        "product_id"
    )

    if existing_product_id is not None:
        try:
            existing_product_id = int(
                existing_product_id
            )
        except (TypeError, ValueError):
            existing_product_id = None

    if existing_product_id is not None and existing_product_id > 0:
        entities["product_id"] = existing_product_id
    else:
        entities.pop("product_id", None)

    # =====================================================
    # Deterministic current-message extraction
    # =====================================================

    explicit_quantity = detect_quantity(
        message
    )

    explicit_address = detect_address_text(
        message
    )

    explicit_address_id = detect_address_id(
        message
    )

    explicit_order_reference = detect_order_reference(message)
    explicit_order_reference_type = detect_order_reference_type(message)

    if explicit_order_id is not None and bool(state.get("awaiting_order_tracking_order_id")):
        explicit_order_reference_type = "specific"

    explicit_payment = detect_payment_method(
        message
    )

    explicit_delivery_preference = detect_delivery_preference(
        message
    )

    explicit_cancellation_reason = detect_cancellation_reason(message)

    if (
        explicit_cancellation_reason is None
        and bool(state.get("awaiting_cancellation_reason"))
        and message.strip()
    ):
        explicit_cancellation_reason = message.strip()

    # Direct product extraction for both ordering and product-search turns.
    # This is only a conservative name extraction; product identity remains
    # backend-authoritative.
    explicit_product = None
    if resolved_current_intent in {
        "order_create",
        "product_search",
        "cart",
    }:
        explicit_product = detect_product_from_message(message)

    if explicit_product:
        entities["product_name"] = explicit_product

    # =====================================================
    # Phase 6B: product candidate selection
    # =====================================================
    #
    # Resolve selection only against backend-derived search results.
    # Never infer a product ID from the user's selection text.
    selected_search_product = _select_product_search_result(
        message=message,
        product_search_results=state.get("product_search_results"),
    )

    if selected_search_product is not None:
        selected_product_id = selected_search_product.get("id")
        if selected_product_id is None:
            selected_product_id = selected_search_product.get("product_id")

        selected_product_name = selected_search_product.get("name")
        if selected_product_name is None:
            selected_product_name = selected_search_product.get("product_name")

        if selected_product_id is not None:
            try:
                selected_product_id = int(selected_product_id)
            except (TypeError, ValueError):
                selected_product_id = None

        if selected_product_id is not None and selected_product_id > 0:
            entities["product_id"] = selected_product_id

        if selected_product_name:
            entities["product_name"] = (
                _clean_product_candidate(selected_product_name)
                or str(selected_product_name).strip()
            )

    elif (
        resolved_current_intent == "cart"
        and existing_entities.get("cart_action") in {"add_item", "remove_item", "update_quantity"}
        and not entities.get("product_name")
    ):
        bare_product = _clean_product_candidate(message)
        if bare_product and bare_product.casefold() not in {"cart", "my cart"}:
            entities["product_name"] = bare_product

    # =====================================================
    # Quantity
    # =====================================================

    if explicit_quantity is not None:

        entities["quantity"] = (
            explicit_quantity
        )

    # =====================================================
    # CRITICAL FIX:
    # Recover quantity from previous USER messages.
    # =====================================================

    elif (
        not new_order
        and checkout_context
    ):

        recovered_quantity = (
            recover_quantity_from_history(
                conversation_history
            )
        )

        if recovered_quantity is not None:

            # Only use history recovery when quantity is
            # not already known.
            if not entities.get(
                "quantity"
            ):

                entities["quantity"] = (
                    recovered_quantity
                )

    # =====================================================
    # New-address action
    # =====================================================

    existing_address_action = str(
        existing_entities.get("address_action") or ""
    ).strip().lower()

    explicit_add_address = bool(
        re.search(
            r"\b(?:add|create|save)\s+(?:a\s+)?(?:new\s+)?address\b|\b(?:new|naya|nayi)\s+address\b",
            message,
            flags=re.IGNORECASE,
        )
    )

    if explicit_add_address:
        entities["address_action"] = "add"
    elif existing_address_action in {"add", "select"}:
        entities["address_action"] = existing_address_action

    # =====================================================
    # New-address fields from structured text
    # =====================================================

    def _extract_address_field(*names: str) -> str | None:
        for name in names:
            match = re.search(
                rf"(?:^|[,;])\s*{re.escape(name)}\s*[:=]\s*([^,;]+)",
                message,
                flags=re.IGNORECASE,
            )
            if match:
                value = match.group(1).strip()
                if value:
                    return value
        return None

    for _field, _value in {
        "address_label": _extract_address_field("label", "address label"),
        "address_line_2": _extract_address_field("address_line_2", "line 2", "landmark"),
        "address_city": _extract_address_field("city"),
        "address_state": _extract_address_field("state"),
        "address_postal_code": _extract_address_field("postal_code", "postal code", "pincode", "pin code"),
    }.items():
        if _value:
            entities[_field] = _value

    # =====================================================
    # Address text
    # =====================================================

    if explicit_address:

        entities["address_text"] = (
            explicit_address
        )

        # Natural-language address does not become a saved
        # address ID.
        if explicit_address_id is None:

            entities.pop(
                "address_id",
                None,
            )

    # =====================================================
    # Explicit address ID
    # =====================================================

    if explicit_address_id is not None:

        entities["address_id"] = (
            explicit_address_id
        )

        entities.pop(
            "address_text",
            None,
        )

    # =====================================================
    # Recover address ID from history
    # =====================================================

    elif (
        not new_order
        and checkout_context
    ):

        recovered_address_id = (
            recover_address_id_from_history(
                conversation_history
            )
        )

        if (
            recovered_address_id is not None
            and not entities.get(
                "address_id"
            )
        ):

            entities["address_id"] = (
                recovered_address_id
            )

    # =====================================================
    # Cancellation Reason
    # =====================================================

    if explicit_cancellation_reason is not None:
        entities["cancellation_reason"] = explicit_cancellation_reason

    # =====================================================
    # Order ID
    # =====================================================

    if explicit_order_id is not None:

        entities["order_id"] = (
            explicit_order_id
        )
        entities["order_reference_type"] = "specific"
        entities.pop("order_reference", None)

    elif explicit_order_reference_type is not None and resolved_current_intent == "order_tracking":
        entities["order_reference_type"] = explicit_order_reference_type
        entities.pop("order_reference", None)
        entities.pop("order_id", None)

    elif explicit_order_reference is not None and resolved_current_intent == "order_tracking":
        entities["order_reference"] = explicit_order_reference
        entities["order_reference_type"] = "specific"

    elif (
        not new_order
        and original_intent in {
            "order_tracking",
            "order_cancel",
        }
    ):

        recovered_order_id = (
            recover_order_id_from_history(
                conversation_history
            )
        )

        if (
            recovered_order_id is not None
            and not entities.get(
                "order_id"
            )
        ):

            entities["order_id"] = (
                recovered_order_id
            )

    # =====================================================
    # Payment
    # =====================================================

    if explicit_payment is not None:

        entities["payment_method"] = (
            explicit_payment
        )

    elif (
        not new_order
        and checkout_context
    ):

        recovered_payment = (
            recover_payment_from_history(
                conversation_history
            )
        )

        if (
            recovered_payment is not None
            and not entities.get(
                "payment_method"
            )
        ):

            entities["payment_method"] = (
                recovered_payment
            )

    # =====================================================
    # Delivery preference
    # =====================================================
    #
    # This is a user preference only. It is deliberately kept as
    # natural-language state and is never translated into a backend
    # delivery option or availability claim.
    # =====================================================

    if explicit_delivery_preference is not None:
        entities["delivery_preference"] = (
            explicit_delivery_preference
        )
    elif (
        not new_order
        and checkout_context
        and existing_entities.get("delivery_preference")
    ):
        entities["delivery_preference"] = (
            existing_entities["delivery_preference"]
        )

    # =====================================================
    # Frontend selected address
    # =====================================================
    #
    # This is AUTHORITATIVE.
    #
    # AddressSelector should send:
    #
    # selected_address_id = 123
    #
    # That value must win over LLM inference.
    #
    # =====================================================

    selected_address_id = (
        state.get(
            "selected_address_id"
        )
    )

    if selected_address_id is not None:

        try:

            normalized_address_id = int(
                selected_address_id
            )

            if normalized_address_id > 0:

                entities["address_id"] = (
                    normalized_address_id
                )

                entities.pop(
                    "address_text",
                    None,
                )

        except (
            TypeError,
            ValueError,
        ):

            print(
                "[ENTITY]"
                " Invalid selected_address_id:"
                f" {selected_address_id!r}"
            )

    # =====================================================
    # Frontend selected payment
    # =====================================================
    #
    # PaymentSelector can send:
    #
    # state["payment_method"]
    #
    # This is authoritative.
    #
    # =====================================================

    selected_payment_method = (
        state.get(
            "payment_method"
        )
    )

    if selected_payment_method:

        normalized_payment = (
            str(
                selected_payment_method
            )
            .strip()
            .lower()
        )

        if normalized_payment in {
            "upi",
            "cod",
        }:

            entities["payment_method"] = (
                normalized_payment
            )

    # =====================================================
    # Normalize payment
    # =====================================================

    if entities.get(
        "payment_method"
    ):

        normalized_payment = (
            str(
                entities[
                    "payment_method"
                ]
            )
            .strip()
            .lower()
        )

        if normalized_payment in {
            "upi",
            "cod",
        }:

            entities["payment_method"] = (
                normalized_payment
            )

        else:

            entities.pop(
                "payment_method",
                None,
            )

    # =====================================================
    # Normalize cart action
    # =====================================================
    #
    # cart_action is intentionally NOT a strict Literal type on
    # LLMEntityOutput/IntentDecision (see class definitions above) --
    # that avoided a provider-side tool-call schema rejection when the
    # model emits the literal text "None" for a null value. Because
    # the field is no longer schema-restricted, validate/restrict it
    # here before it is trusted anywhere downstream (missing-field
    # logic, planner, tool node).
    # =====================================================

    if entities.get("cart_action"):

        normalized_cart_action = (
            str(entities["cart_action"]).strip().lower()
        )

        allowed_cart_actions = {
            "add_item",
            "remove_item",
            "update_quantity",
            "clear_cart",
            "show_cart",
            "checkout",
        }

        if normalized_cart_action in allowed_cart_actions:
            entities["cart_action"] = normalized_cart_action
        else:
            entities.pop("cart_action", None)

    multi_item_order = _extract_multi_item_order(message)
    if multi_item_order and len(multi_item_order) >= 2:
        entities["items"] = multi_item_order
        entities["product_name"] = multi_item_order[0]["product_name"]
        entities["quantity"] = multi_item_order[0]["quantity"]

    # =====================================================
    # Product fallback
    # =====================================================

    if not entities.get(
        "product_name"
    ):

        product = detect_product_fallback(
            message=message,
            conversation_history=conversation_history,
        )

        if product:

            entities["product_name"] = (
                product
            )

    # =====================================================
    # Normalize product
    # =====================================================

    if entities.get(
        "product_name"
    ):

        entities["product_name"] = (
            str(
                entities[
                    "product_name"
                ]
            )
            .strip()
        )

    # =====================================================
    # Product identity consistency
    # =====================================================
    #
    # If the user changed the product name, the previous product_id
    # is no longer valid. The later tool node must resolve the new
    # product name and write the new authoritative product_id.
    #
    current_product_name = entities.get(
        "product_name"
    )

    if (
        existing_product_id is not None
        and previous_product_name
        and current_product_name
        and str(previous_product_name).strip().casefold()
        != str(current_product_name).strip().casefold()
    ):
        entities.pop(
            "product_id",
            None,
        )

    # If there is no product name at all, do not carry a stale ID.
    if not current_product_name:
        entities.pop(
            "product_id",
            None,
        )

    # =====================================================
    # Product ID safety
    # =====================================================

    if entities.get("product_id") is not None:
        try:
            product_id = int(
                entities["product_id"]
            )

            if product_id > 0:
                entities["product_id"] = product_id
            else:
                entities.pop(
                    "product_id",
                    None,
                )

        except (TypeError, ValueError):
            entities.pop(
                "product_id",
                None,
            )

    # =====================================================
    # Quantity safety
    # =====================================================

    if entities.get(
        "quantity"
    ) is not None:

        try:

            quantity = int(
                entities[
                    "quantity"
                ]
            )

            if quantity > 0:

                entities["quantity"] = (
                    quantity
                )

            else:

                entities.pop(
                    "quantity",
                    None,
                )

        except (
            TypeError,
            ValueError,
        ):

            entities.pop(
                "quantity",
                None,
            )

    # =====================================================
    # Address ID safety
    # =====================================================

    if entities.get(
        "address_id"
    ) is not None:

        try:

            address_id = int(
                entities[
                    "address_id"
                ]
            )

            if address_id > 0:

                entities["address_id"] = (
                    address_id
                )

            else:

                entities.pop(
                    "address_id",
                    None,
                )

        except (
            TypeError,
            ValueError,
        ):

            entities.pop(
                "address_id",
                None,
            )

    # =====================================================
    # Order ID safety
    # =====================================================

    if entities.get(
        "order_id"
    ) is not None:

        try:

            order_id = int(
                entities[
                    "order_id"
                ]
            )

            if order_id > 0:

                entities["order_id"] = (
                    order_id
                )

            else:

                entities.pop(
                    "order_id",
                    None,
                )

        except (
            TypeError,
            ValueError,
        ):

            entities.pop(
                "order_id",
                None,
            )

    # =====================================================
    # Order reference safety
    # =====================================================

    reference_type = entities.get("order_reference_type")
    if reference_type not in {"specific", "latest", "previous"}:
        entities.pop("order_reference_type", None)

    order_reference = entities.get("order_reference")
    if order_reference is not None:
        order_reference = str(order_reference).strip()
        if order_reference:
            entities["order_reference"] = order_reference
        else:
            entities.pop("order_reference", None)

    # =====================================================
    # FINAL CURRENT-TURN INTENT
    # =====================================================
    #
    # Do not run a second deterministic intent override here.
    # The AI decision above is authoritative for the current turn.
    # =====================================================

    resolved_intent = (
        resolved_current_intent
    )

    if (
        bool(state.get("awaiting_cancellation_reason"))
        and message.strip()
    ):
        if not entities.get("cancellation_reason"):
            entities["cancellation_reason"] = message.strip()
        resolved_intent = "order_cancel"

    # =====================================================
    # Build final structured entity object
    # =====================================================

    resolved_entities = EntityOutput(
        items=entities.get("items"),
        product_id=entities.get(
            "product_id"
        ),
        product_name=entities.get(
            "product_name"
        ),
        quantity=entities.get(
            "quantity"
        ),
        order_id=entities.get(
            "order_id"
        ),
        order_reference=entities.get("order_reference"),
        order_reference_type=entities.get("order_reference_type"),
        cancellation_reason=entities.get("cancellation_reason"),
        address_id=entities.get(
            "address_id"
        ),
        address_text=entities.get(
            "address_text"
        ),
        address_action=entities.get("address_action"),
        address_label=entities.get("address_label"),
        address_line_2=entities.get("address_line_2"),
        address_city=entities.get("address_city"),
        address_state=entities.get("address_state"),
        address_postal_code=entities.get("address_postal_code"),
        payment_method=entities.get(
            "payment_method"
        ),
        delivery_preference=entities.get(
            "delivery_preference"
        ),
        cart_action=entities.get(
            "cart_action"
        ),
    )

    # =====================================================
    # Determine missing fields
    # =====================================================

    missing_fields = (
        get_missing_fields(
            intent=resolved_intent,
            entities=resolved_entities,
        )
    )

    # =====================================================
    # Debug Logging
    # =====================================================

    final_entities = (
        resolved_entities.model_dump(
            exclude_none=True
        )
    )

    print(
        "\n"
        "[ENTITY NODE]"
        "\n"
        f"  message          = {message!r}"
        "\n"
        f"  intent_before    = {original_intent!r}"
        "\n"
        f"  intent_after     = {resolved_intent!r}"
        "\n"
        f"  order_action      = {intent_decision.order_action!r}"
        "\n"
        f"  intent_confidence = {intent_decision.confidence!r}"
        "\n"
        f"  new_order        = {new_order}"
        "\n"
        f"  selected_address = {selected_address_id!r}"
        "\n"
        f"  product_id       = {final_entities.get('product_id')!r}"
        "\n"
        f"  selected_product = {selected_search_product!r}"
        "\n"
        f"  entities         = {final_entities}"
        "\n"
        f"  missing_fields   = {missing_fields}"
        "\n"
    )

    # =====================================================
    # Return Graph Updates
    # =====================================================

    return {
        "intent": resolved_intent,

        "entities": final_entities,

        # Convenience mirrors for downstream graph/tool nodes.
        # The authoritative product_id still comes from backend
        # resolution, never from the LLM.
        "product_id": final_entities.get("product_id"),
        "product_name": final_entities.get("product_name"),
        "quantity": final_entities.get("quantity"),
        "order_id": final_entities.get("order_id"),
        "order_reference": final_entities.get("order_reference"),
        "order_reference_type": final_entities.get("order_reference_type"),
        "cancellation_reason": final_entities.get("cancellation_reason"),
        "awaiting_order_tracking_order_id": bool(
            resolved_intent == "order_tracking"
            and not (
                final_entities.get("order_id")
                or final_entities.get("order_reference")
                or final_entities.get("order_reference_type") in {"latest", "previous"}
            )
        ),
        "awaiting_cancellation_reason": bool(
            resolved_intent == "order_cancel"
            and bool((state.get("cancellation_eligibility") or {}).get("eligible"))
            and not final_entities.get("cancellation_reason")
        ),
        "address_id": final_entities.get("address_id"),
        "address_action": final_entities.get("address_action"),
        "address_label": final_entities.get("address_label"),
        "address_line_2": final_entities.get("address_line_2"),
        "address_city": final_entities.get("address_city"),
        "address_state": final_entities.get("address_state"),
        "address_postal_code": final_entities.get("address_postal_code"),

        # Phase 6B: preserve the backend-derived selected candidate.
        **(
            {"selected_product": selected_search_product}
            if selected_search_product is not None
            else {}
        ),
        "payment_method": final_entities.get(
            "payment_method"
        ),
        "delivery_preference": final_entities.get(
            "delivery_preference"
        ),

        # Transaction identity/state must survive every HTTP turn.
        "checkout_id": checkout_id,
        "checkout_status": checkout_status,
        "order_created": order_created,
        "checkout_completed": bool(
            checkout_status == "completed" or order_created
        ),

        "missing_fields": missing_fields,
    }