def _is_payment_selection(
    message: str,
) -> bool:

    return (
        detect_payment_method(
            message
        )
        is not None
    )


# =========================================================
# Address Selection
# =========================================================


def _is_address_selection(
    state: GraphState,
    message: str,
) -> bool:

    if (
        state.get(
            "selected_address_id"
        )
        is not None
    ):
        return True

    if (
        detect_address_id(
            message
        )
        is not None
    ):
        return True

    text = (
        message or ""
    ).lower()

    return any(
        phrase in text
        for phrase in (
            "selected delivery address",
            "use the selected address",
            "use selected address",
            "use this address",
            "address selected",
        )
    )


# =========================================================
# Active Checkout Detection
# =========================================================


def _is_active_order_checkout(
    state: GraphState,
    entities: dict[str, Any],
    message: str,
) -> bool:
    """
    Determine whether the current turn belongs to an
    active order checkout.
    """

    # Explicit commands have priority.
    if _is_explicit_tracking_request(
        message
    ):
        return False

    if _is_explicit_cancel_request(
        message
    ):
        return False

    if _is_explicit_support_request(
        message
    ):
        return False

    # Explicitly starting a new order.
    if _is_new_order_request(
        message
    ):
        return True

    current_intent = state.get(
        "intent",
        "general",
    )

    if current_intent == "order_create":
        return True

    # Do not convert a normal product-search turn into checkout
    # merely because a product name was extracted.
    if current_intent == "product_search":
        return False

    existing_entities = (
        state.get(
            "entities",
            {},
        )
        or {}
    )

    product_id = entities.get("product_id")
    if product_id is None:
        product_id = existing_entities.get("product_id")

    product_name = entities.get("product_name")
    if not _has_value(product_name):
        product_name = existing_entities.get("product_name")

    quantity = entities.get("quantity")
    if quantity is None:
        quantity = existing_entities.get("quantity")

    address_id = state.get("selected_address_id")
    if address_id is None:
        address_id = entities.get("address_id")
    if address_id is None:
        address_id = existing_entities.get("address_id")

    payment_method = entities.get("payment_method")
    if not _has_value(payment_method):
        payment_method = existing_entities.get("payment_method")

    # A resolved product ID is the strongest checkout signal.
    if _has_value(product_id):
        return True

    # Product name is also a checkout signal before backend resolution.
    if _has_value(
        product_name
    ):
        return True

    # Quantity continuation.
    if _has_value(
        quantity
    ):
        return True

    # Address selection continuation.
    if _is_address_selection(
        state,
        message,
    ):
        return True

    # Payment continuation.
    if _is_payment_selection(
        message
    ):
        return True

    if (
        _has_value(
            payment_method
        )
        and (
            _has_value(
                product_name
            )
            or _has_value(
                quantity
            )
            or _has_value(
                address_id
            )
        )
    ):
        return True

    return False


# =========================================================
# Intent Resolution
# =========================================================


def resolve_transaction_intent(
    state: GraphState,
    entities: dict[str, Any],
    message: str,
) -> str:

    llm_intent = state.get(
        "intent",
        "general",
    )

    clean_message = (
        message or ""
    ).strip()

    # -----------------------------------------------------
    # 1. Explicit tracking
    # -----------------------------------------------------

    if _is_explicit_tracking_request(
        clean_message
    ):
        return "order_tracking"

    # -----------------------------------------------------
    # 2. Explicit cancellation
    # -----------------------------------------------------

    if _is_explicit_cancel_request(
        clean_message
    ):
        return "order_cancel"

    # -----------------------------------------------------
    # 3. Explicit support
    # -----------------------------------------------------

    if _is_explicit_support_request(
        clean_message
    ):
        return "customer_support"

    # -----------------------------------------------------
    # 4. Active checkout
    # -----------------------------------------------------

    if _is_active_order_checkout(
        state=state,
        entities=entities,
        message=clean_message,
    ):
        return "order_create"

    # -----------------------------------------------------
    # 5. Valid existing intent
    # -----------------------------------------------------

    valid_intents = {
        "product_search",
        "order_tracking",
        "order_cancel",
        "customer_support",
        "order_create",
        "general",
    }

    if llm_intent in valid_intents:
        return llm_intent

    return "general"


# =========================================================
# Missing Fields
# =========================================================


def get_missing_fields(
    intent: str,
    entities: EntityOutput,
) -> list[str]:
    """
    Determine missing checkout fields.

    IMPORTANT:
    The order of this list is intentional.

    Product
      ↓
    Quantity
      ↓
    Address
      ↓
    Payment

    Response node should ask only the FIRST missing field.
    """

    missing: list[str] = []

    # =====================================================
    # Product Search
    # =====================================================

    if intent == "product_search":

        if not entities.product_name:
            missing.append(
                "product_name"
            )

    # =====================================================
    # Order Creation
    # =====================================================

    elif intent == "order_create":

        # Product
        if (
            entities.product_id is None
            and not entities.product_name
        ):

            missing.append(
                "product_name"
            )

        # Quantity
        elif (
            entities.quantity is None
            or entities.quantity <= 0
        ):

            missing.append(
                "quantity"
            )

        # Address
        elif entities.address_id is None:

            missing.append(
                "address_selection"
            )

        # Payment
        elif not entities.payment_method:

            missing.append(
                "payment_method"
            )

    # =====================================================
    # Tracking
    # =====================================================

    elif intent == "order_tracking":

        if entities.order_id is None:

            missing.append(
                "order_id"
            )

    # =====================================================
    # Cancellation
    # =====================================================

    elif intent == "order_cancel":

        if entities.order_id is None:

            missing.append(
                "order_id"
            )

    return missing


# =========================================================
# LLM Entity Extraction
# =========================================================


def extract_entities(
    message: str,
    conversation_history: list[dict[str, Any]] | None = None,
) -> LLMEntityOutput:
    """
    Extract LLM-safe entities.

    product_id is intentionally not part of this model.


    Deterministic history recovery happens separately so
    critical checkout values do not depend entirely on the
    LLM.
    """

    if not message or not message.strip():

        return LLMEntityOutput()

    clean_message = message.strip()

    history_text = format_conversation_history(
        conversation_history
    )

    messages = [
        SystemMessage(
            content=ENTITY_SYSTEM_PROMPT
        ),

        HumanMessage(
            content=(
                "RECENT CONVERSATION:\n"
                "--------------------\n"
                f"{history_text}\n\n"

                "CURRENT USER MESSAGE:\n"
                "--------------------\n"
                f"{clean_message}\n\n"

                "Return the COMPLETE accumulated entity "
                "state. Preserve previous checkout values."
            )
        ),
    ]

    try:

        result: LLMEntityOutput = (
            structured_llm.invoke(
                messages
            )
        )

        if not isinstance(
            result,
            LLMEntityOutput,
        ):
            return LLMEntityOutput()

        return result

    except Exception as exc:

        print(
            "[ENTITY LLM ERROR]"
            f" {type(exc).__name__}: {exc}"
        )

        return LLMEntityOutput()


# =========================================================
# Entity Node
# =========================================================


def entity_node(
    state: GraphState,
) -> GraphState:
    """
    Main BuyQK entity-resolution node.

    This is intentionally deterministic around checkout
    state.

    Critical example:

        User:
            I want to order Amul milk

        Assistant:
            How much Amul milk would you like?

        User:
            3 packets

        Assistant:
            Please choose your delivery address.

        User:
            Use the selected delivery address.

    Final state MUST contain:

        product_name = Amul milk
        quantity = 3
        address_id = selected address

    and NOT ask for quantity again.
    """

    message = (
        state.get(
            "message",
            "",
        )
        or ""
    ).strip()

    original_intent = state.get(
        "intent",
        "general",
    )

    conversation_history = (
        state.get(
            "conversation_history",
            [],
        )
        or []
    )

    existing_entities = dict(
        state.get(
            "entities",
            {},
        )
        or {}
    )

    # =====================================================
    # New order reset
    # =====================================================
    #
    # If the user explicitly starts another order, don't
    # accidentally reuse the quantity/address/payment from
    # the previous completed order.
    #
    # =====================================================

    new_order = _is_new_order_request(
        message
    )

    # Only recover checkout fields from history while the graph is
    # actually in an order-creation flow. This prevents quantities,
    # addresses, and payment methods from old orders leaking into
    # unrelated product-search turns.
    checkout_context = (
        original_intent == "order_create"
        or _is_address_selection(
            state,
            message,
        )
        or _is_payment_selection(
            message
        )
    )

    if new_order:

        # Clear every order-specific value.
        # The new message will establish the new product.
        existing_entities.pop(
            "product_id",
            None,
        )

        existing_entities.pop(
            "product_name",
            None,
        )

        existing_entities.pop(
            "quantity",
            None,
        )

        existing_entities.pop(
            "address_id",
            None,
        )

        existing_entities.pop(
            "address_text",
            None,
        )

        existing_entities.pop(
            "payment_method",
            None,
        )

        existing_entities.pop(
            "order_id",
            None,
        )

    # =====================================================
    # LLM extraction
    # =====================================================

    extracted = extract_entities(
        message=message,
        conversation_history=conversation_history,
    )

    extracted_entities = (
        extracted.model_dump(
            exclude_none=True
        )
    )

    # =====================================================
    # Merge existing graph state
    # =====================================================

    entities = dict(
        existing_entities
    )

    for key, value in extracted_entities.items():

        if value is not None:

            entities[key] = value

    # =====================================================
    # IMPORTANT PRODUCT-ID RULE
    # =====================================================
    #
    # product_id is backend authoritative. The LLM model does not
    # contain this field, so it cannot overwrite it here.
    # Preserve an existing backend-resolved ID until the user
    # explicitly changes the product.
    #
    previous_product_name = existing_entities.get(
        "product_name"
    )
    existing_product_id = existing_entities.get(
        "product_id"
    )

    if existing_product_id is not None:
        try:
            existing_product_id = int(
                existing_product_id
            )
        except (TypeError, ValueError):
            existing_product_id = None

    if existing_product_id is not None and existing_product_id > 0:
        entities["product_id"] = existing_product_id
    else:
        entities.pop("product_id", None)

    # =====================================================
    # Deterministic current-message extraction
    # =====================================================

    explicit_quantity = detect_quantity(
        message
    )

    explicit_address = detect_address_text(
        message
    )

    explicit_address_id = detect_address_id(
        message
    )

    explicit_order_id = detect_order_id(
        message
    )

    explicit_payment = detect_payment_method(
        message
    )

    # =====================================================
    # Quantity
    # =====================================================

    if explicit_quantity is not None:

        entities["quantity"] = (
            explicit_quantity
        )

    # =====================================================
    # CRITICAL FIX:
    # Recover quantity from previous USER messages.
    # =====================================================

    elif (
        not new_order
        and checkout_context
    ):

        recovered_quantity = (
            recover_quantity_from_history(
                conversation_history
            )
        )

        if recovered_quantity is not None:

            # Only use history recovery when quantity is
            # not already known.
            if not entities.get(
                "quantity"
            ):

                entities["quantity"] = (
                    recovered_quantity
                )

    # =====================================================
    # Address text
    # =====================================================

    if explicit_address:

        entities["address_text"] = (
            explicit_address
        )

        # Natural-language address does not become a saved
        # address ID.
        if explicit_address_id is None:

            entities.pop(
                "address_id",
                None,
            )

    # =====================================================
    # Explicit address ID
    # =====================================================

    if explicit_address_id is not None:

        entities["address_id"] = (
            explicit_address_id
        )

        entities.pop(
            "address_text",
            None,
        )

    # =====================================================
    # Recover address ID from history
    # =====================================================

    elif (
        not new_order
        and checkout_context
    ):

        recovered_address_id = (
            recover_address_id_from_history(
                conversation_history
            )
        )

        if (
            recovered_address_id is not None
            and not entities.get(
                "address_id"
            )
        ):

            entities["address_id"] = (
                recovered_address_id
            )

    # =====================================================
    # Order ID
    # =====================================================

    if explicit_order_id is not None:

        entities["order_id"] = (
            explicit_order_id
        )

    elif (
        not new_order
        and original_intent in {
            "order_tracking",
            "order_cancel",
        }
    ):

        recovered_order_id = (
            recover_order_id_from_history(
                conversation_history
            )
        )

        if (
            recovered_order_id is not None
            and not entities.get(
                "order_id"
            )
        ):

            entities["order_id"] = (
                recovered_order_id
            )

    # =====================================================
    # Payment
    # =====================================================

    if explicit_payment is not None:

        entities["payment_method"] = (
            explicit_payment
        )

    elif (
        not new_order
        and checkout_context
    ):

        recovered_payment = (
            recover_payment_from_history(
                conversation_history
            )
        )

        if (
            recovered_payment is not None
            and not entities.get(
                "payment_method"
            )
        ):

            entities["payment_method"] = (
                recovered_payment
            )

    # =====================================================
    # Frontend selected address
    # =====================================================
    #
    # This is AUTHORITATIVE.
    #
    # AddressSelector should send:
    #
    # selected_address_id = 123
    #
    # That value must win over LLM inference.
    #
    # =====================================================

    selected_address_id = (
        state.get(
            "selected_address_id"
        )
    )

    if selected_address_id is not None:

        try:

            normalized_address_id = int(
                selected_address_id
            )

            if normalized_address_id > 0:

                entities["address_id"] = (
                    normalized_address_id
                )

                entities.pop(
                    "address_text",
                    None,
                )

        except (
            TypeError,
            ValueError,
        ):

            print(
                "[ENTITY]"
                " Invalid selected_address_id:"
                f" {selected_address_id!r}"
            )

    # =====================================================
    # Frontend selected payment
    # =====================================================
    #
    # PaymentSelector can send:
    #
    # state["payment_method"]
    #
    # This is authoritative.
    #
    # =====================================================

    selected_payment_method = (
        state.get(
            "payment_method"
        )
    )

    if selected_payment_method:

        normalized_payment = (
            str(
                selected_payment_method
            )
            .strip()
            .lower()
        )

        if normalized_payment in {
            "upi",
            "cod",
        }:

            entities["payment_method"] = (
                normalized_payment
            )

    # =====================================================
    # Normalize payment
    # =====================================================

    if entities.get(
        "payment_method"
    ):

        normalized_payment = (
            str(
                entities[
                    "payment_method"
                ]
            )
            .strip()
            .lower()
        )

        if normalized_payment in {
            "upi",
            "cod",
        }:

            entities["payment_method"] = (
                normalized_payment
            )

        else:

            entities.pop(
                "payment_method",
                None,
            )

    # =====================================================
    # Product fallback
    # =====================================================

    if not entities.get(
        "product_name"
    ):

        product = detect_product_fallback(
            message=message,
            conversation_history=conversation_history,
        )

        if product:

            entities["product_name"] = (
                product
            )

    # =====================================================
    # Normalize product
    # =====================================================

    if entities.get(
        "product_name"
    ):

        entities["product_name"] = (
            str(
                entities[
                    "product_name"
                ]
            )
            .strip()
        )

    # =====================================================
    # Product identity consistency
    # =====================================================
    #
    # If the user changed the product name, the previous product_id
    # is no longer valid. The later tool node must resolve the new
    # product name and write the new authoritative product_id.
    #
    current_product_name = entities.get(
        "product_name"
    )

    if (
        existing_product_id is not None
        and previous_product_name
        and current_product_name
        and str(previous_product_name).strip().casefold()
        != str(current_product_name).strip().casefold()
    ):
        entities.pop(
            "product_id",
            None,
        )

    # If there is no product name at all, do not carry a stale ID.
    if not current_product_name:
        entities.pop(
            "product_id",
            None,
        )

    # =====================================================
    # Product ID safety
    # =====================================================

    if entities.get("product_id") is not None:
        try:
            product_id = int(
                entities["product_id"]
            )

            if product_id > 0:
                entities["product_id"] = product_id
            else:
                entities.pop(
                    "product_id",
                    None,
                )

        except (TypeError, ValueError):
            entities.pop(
                "product_id",
                None,
            )

    # =====================================================
    # Quantity safety
    # =====================================================

    if entities.get(
        "quantity"
    ) is not None:

        try:

            quantity = int(
                entities[
                    "quantity"
                ]
            )

            if quantity > 0:

                entities["quantity"] = (
                    quantity
                )

            else:

                entities.pop(
                    "quantity",
                    None,
                )

        except (
            TypeError,
            ValueError,
        ):

            entities.pop(
                "quantity",
                None,
            )

    # =====================================================
    # Address ID safety
    # =====================================================

    if entities.get(
        "address_id"
    ) is not None:

        try:

            address_id = int(
                entities[
                    "address_id"
                ]
            )

            if address_id > 0:

                entities["address_id"] = (
                    address_id
                )

            else:

                entities.pop(
                    "address_id",
                    None,
                )

        except (
            TypeError,
            ValueError,
        ):

            entities.pop(
                "address_id",
                None,
            )

    # =====================================================
    # Order ID safety
    # =====================================================

    if entities.get(
        "order_id"
    ) is not None:

        try:

            order_id = int(
                entities[
                    "order_id"
                ]
            )

            if order_id > 0:

                entities["order_id"] = (
                    order_id
                )

            else:

                entities.pop(
                    "order_id",
                    None,
                )

        except (
            TypeError,
            ValueError,
        ):

            entities.pop(
                "order_id",
                None,
            )

    # =====================================================
    # Resolve final intent
    # =====================================================

    resolved_intent = (
        resolve_transaction_intent(
            state=state,
            entities=entities,
            message=message,
        )
    )

    # =====================================================
    # Build final structured entity object
    # =====================================================

    resolved_entities = EntityOutput(
        product_id=entities.get(
            "product_id"
        ),
        product_name=entities.get(
            "product_name"
        ),
        quantity=entities.get(
            "quantity"
        ),
        order_id=entities.get(
            "order_id"
        ),
        address_id=entities.get(
            "address_id"
        ),
        address_text=entities.get(
            "address_text"
        ),
        payment_method=entities.get(
            "payment_method"
        ),
    )

    # =====================================================
    # Determine missing fields
    # =====================================================

    missing_fields = (
        get_missing_fields(
            intent=resolved_intent,
            entities=resolved_entities,
        )
    )

    # =====================================================
    # Debug Logging
    # =====================================================

    final_entities = (
        resolved_entities.model_dump(
            exclude_none=True
        )
    )

    print(
        "\n"
        "[ENTITY NODE]"
        "\n"
        f"  message          = {message!r}"
        "\n"
        f"  intent_before    = {original_intent!r}"
        "\n"
        f"  intent_after     = {resolved_intent!r}"
        "\n"
        f"  new_order        = {new_order}"
        "\n"
        f"  selected_address = {selected_address_id!r}"
        "\n"
        f"  product_id       = {final_entities.get('product_id')!r}"
        "\n"
        f"  entities         = {final_entities}"
        "\n"
        f"  missing_fields   = {missing_fields}"
        "\n"
    )

    # =====================================================
    # Return Graph Updates
    # =====================================================

    return {
        "intent": resolved_intent,

        "entities": final_entities,

        # Convenience mirrors for downstream graph/tool nodes.
        # The authoritative product_id still comes from backend
        # resolution, never from the LLM.
        "product_id": final_entities.get("product_id"),
        "product_name": final_entities.get("product_name"),
        "quantity": final_entities.get("quantity"),
        "address_id": final_entities.get("address_id"),
        "payment_method": final_entities.get(
            "payment_method"
        ),

        "missing_fields": missing_fields,
    }