# Deterministic Cart Action Detection
# =========================================================

_CART_ACTION_PATTERNS: list[tuple[str, str]] = [
    # Order matters: check clear/show/checkout before add/remove so a
    # phrase like "show my cart" is never mistaken for "add"/"remove".
    (r"\bclear\b.*\bcart\b", "clear_cart"),
    (r"\bempty\b.*\bcart\b", "clear_cart"),
    (r"\bshow\b.*\bcart\b", "show_cart"),
    (r"\bview\b.*\bcart\b", "show_cart"),
    (r"what.?s\s+in\s+(?:my\s+|the\s+)?cart", "show_cart"),
    (r"\bcheck\s*out\b", "checkout"),
    (r"\bcheckout\b", "checkout"),
    (r"\bremove\b|\bdelete\b|\btake\s+out\b", "remove_item"),
    (
        r"\bchange\b.*\bquantity\b"
        r"|\bupdate\b.*\bquantity\b"
        r"|\bmake\s+it\b",
        "update_quantity",
    ),
    (r"\badd\b|\bput\b|\binclude\b", "add_item"),
]


def detect_cart_action_from_message(
    message: str,
) -> Optional[str]:
    """
    Deterministically detect the requested cart operation from the
    CURRENT message, without any LLM call.

    This does not resolve product identity or quantities -- it only
    identifies WHICH cart operation is being requested, so entity_node
    can decide whether an LLM extraction call is still needed (it is,
    for add/remove/update, to resolve product_name/quantity; it is
    not, for clear/show/checkout).
    """

    if not message:
        return None

    text = message.strip().lower()

    if not text:
        return None

    for pattern, action in _CART_ACTION_PATTERNS:
        if re.search(pattern, text, flags=re.IGNORECASE):
            return action

    return None


# =========================================================
# Product Message Detection
# =========================================================

def _clean_product_candidate(value: Any) -> Optional[str]:
    """Normalize a candidate product phrase without knowing catalog names."""
    if value is None:
        return None

    candidate = re.sub(r"\s+", " ", str(value).strip())
    candidate = candidate.strip(" \t\r\n.,!?;:()[]{}\"'")

    if not candidate:
        return None

    # Remove a leading quantity/unit phrase:
    # "2 kg sugar" -> "sugar"
    # "3 packets Maggi" -> "Maggi"
    candidate = re.sub(
        r"^\d+(?:\.\d+)?\s*"
        r"(?:kg|kgs|kilograms?|g|grams?|l|litres?|liters?|ml|"
        r"packets?|packs?|pieces?|pcs?|items?|units?)\s+",
        "",
        candidate,
        flags=re.IGNORECASE,
    )
    candidate = re.sub(r"^\d+(?:\.\d+)?\s+", "", candidate).strip()

    # Remove common conversational suffixes.
    candidate = re.sub(
        r"\s+(?:please|plz|pls|na|ji|hai|h)\s*$",
        "",
        candidate,
        flags=re.IGNORECASE,
    ).strip()

    if not candidate:
        return None

    # Never turn a reference/pronoun into a product name.
    if candidate.casefold() in {
        "it",
        "this",
        "that",
        "these",
        "those",
        "same",
        "same one",
        "one",
        "another",
        "another one",
        "something",
        "anything",
        "nothing",
        "that one",
        "this one",
        "selected item",
        "selected product",
    }:
        return None

    # Guard against transactional continuation values.
    if detect_payment_method(candidate) is not None:
        return None
    if detect_address_id(candidate) is not None:
        return None
    if detect_address_text(candidate) is not None:
        return None
    if detect_quantity(candidate, allow_plain_number=True) is not None:
        return None

    return candidate


def _extract_multi_item_order(
    message: str,
) -> Optional[list[dict[str, Any]]]:
    """Parse repeated product/quantity pairs from a single order message."""
    if not message:
        return None

    text = re.sub(r"\s+", " ", str(message).strip())
    if not text:
        return None

    candidate = text
    for prefix in (
        r"^(?:i\s+(?:want|need|would\s+like)\s+(?:to\s+)?(?:order|buy|get|purchase)\s+)",
        r"^(?:please\s+)?(?:order|buy|get|purchase)\s+",
        r"^(?:i\s+(?:want|need)\s+)",
        r"^(?:i\s+(?:would\s+like)\s+)",
    ):
        candidate = re.sub(prefix, "", candidate, count=1, flags=re.IGNORECASE)
        if candidate != text:
            break

    if not candidate or candidate == text:
        candidate = text

    segments = re.split(r"\s+(?:and|plus|&|\+|,|\bthen\b)\s+", candidate, flags=re.IGNORECASE)
    items: list[dict[str, Any]] = []

    for segment in segments:
        segment = segment.strip()
        if not segment:
            continue

        quantity_match = re.match(
            r"^\s*(\d+(?:\.\d+)?)\s*(?:kg|kgs|kilograms?|g|grams?|l|litres?|liters?|ml|packets?|packs?|pieces?|pcs?|items?|units?)?\s*(.*)$",
            segment,
            flags=re.IGNORECASE,
        )

        if quantity_match is None:
            quantity = detect_quantity(segment, allow_plain_number=True)
            if quantity is None:
                continue
            product_candidate = segment
        else:
            quantity = int(quantity_match.group(1))
            product_candidate = quantity_match.group(2).strip()

        if quantity <= 0:
            continue

        if not product_candidate:
            continue

        product_candidate = re.sub(r"^(?:of|the)\s+", "", product_candidate, flags=re.IGNORECASE).strip()
        if not product_candidate or detect_quantity(product_candidate, allow_plain_number=True) is not None:
            continue
        if detect_address_text(product_candidate) is not None or detect_payment_method(product_candidate) is not None:
            continue

        cleaned_product = _clean_product_candidate(product_candidate)
        if cleaned_product:
            items.append({"product_name": cleaned_product, "quantity": quantity})

    if len(items) >= 2:
        return items
    return None


def detect_product_from_message(
    message: str,
) -> Optional[str]:
    """
    Extract an explicit product phrase from the CURRENT message.

    This is catalog-agnostic: it recognizes language constructions rather
    than maintaining a hard-coded list of product names.

    Examples:
        "I want to buy rice"       -> "rice"
        "buy 2 kg sugar"           -> "sugar"
        "mujhe biscuits chahiye"   -> "biscuits"
        "Mujhe Sugar kharidna h"   -> "Sugar"
        "show me toothpaste"      -> "toothpaste"
    """
    if not message or not str(message).strip():
        return None

    multi_items = _extract_multi_item_order(message)
    if multi_items and len(multi_items) >= 2:
        return multi_items[0]["product_name"]

    text = re.sub(r"\s+", " ", str(message).strip())

    patterns = (
        # English purchase/order constructions.
        r"^\s*i\s+(?:want|need)\s+to\s+(?:order|buy|get|purchase)\s+(.+?)\s*$",
        r"^\s*i\s+(?:want|need)\s+(?:to\s+)?(?:order|buy|get|purchase)\s+(.+?)\s*$",
        r"^\s*i(?:'d|\s+would)\s+like\s+to\s+(?:order|buy|get|purchase)\s+(.+?)\s*$",
        r"^\s*(?:please\s+)?(?:order|buy|purchase|get)\s+(.+?)\s*$",
        r"^\s*i\s+(?:want|need)\s+(.+?)\s*$",
        r"^\s*i(?:'d|\s+would)\s+like\s+(.+?)\s*$",

        # English browse/search constructions.
        r"^\s*(?:please\s+)?show\s+me\s+(.+?)\s*$",
        r"^\s*(?:please\s+)?(?:find|search\s+for|look\s+for)\s+(.+?)\s*$",
        r"^\s*(?:i\s+am|i'm)\s+looking\s+for\s+(.+?)\s*$",
        r"^\s*can\s+you\s+(?:show|find|get)\s+(?:me\s+)?(.+?)\s*$",

        # Hindi / Hinglish purchase constructions.
        r"^\s*(?:mujhe|mujhko)\s+(.+?)\s+(?:kharidna|khareedna|kharidne)\s+(?:hai|h)\s*$",
        r"^\s*(?:mujhe|mujhko)\s+(.+?)\s+(?:lena|lenā|lene)\s+(?:hai|h)\s*$",
        r"^\s*(?:mujhe|mujhko)\s+(.+?)\s+(?:chahiye|chaahiye)\s*$",
        r"^\s*(?:mujhe|mujhko)\s+(.+?)\s+(?:dikhao|dikhaiye|dikha\s+do|dikhana)\s*$",
        r"^\s*(?:mujhe|mujhko)\s+(.+?)\s+(?:do|de\s+do)\s*$",
    )

    for pattern in patterns:
        match = re.search(pattern, text, flags=re.IGNORECASE)
        if not match:
            continue

        candidate = _clean_product_candidate(match.group(1))
        if candidate:
            return candidate

    return None


# =========================================================
# Product Search Result Selection - Phase 6B
# =========================================================


def _selection_index_from_message(
    message: str,
) -> Optional[int]:
    """
    Extract a 1-based product-candidate position from a selection message.

    This is catalog-agnostic. It only interprets an explicit ordinal or
    option number; it never invents or resolves product identity.
    """
    text = re.sub(r"\s+", " ", (message or "").strip().lower())
    if not text:
        return None

    patterns = (
        r"\boption\s*#?\s*(\d+)\b",
        r"\b(?:number|no\.?)\s*#?\s*(\d+)\b",
        r"\b(?:product|item)\s*#?\s*(\d+)\b",
        r"\b(\d+)(?:st|nd|rd|th)\s+(?:one|option|product|item)\b",
    )

    for pattern in patterns:
        match = re.search(pattern, text, flags=re.IGNORECASE)
        if match:
            try:
                index = int(match.group(1))
            except (TypeError, ValueError):
                return None
            return index if index > 0 else None

    ordinal_words = {
        "first": 1,
        "second": 2,
        "third": 3,
        "fourth": 4,
        "fifth": 5,
        "sixth": 6,
        "seventh": 7,
        "eighth": 8,
        "ninth": 9,
        "tenth": 10,
    }

    for word, index in ordinal_words.items():
        if re.search(
            rf"\b{word}\s+(?:one|option|product|item)\b",
            text,
            flags=re.IGNORECASE,
        ):
            return index

    # Hindi / Hinglish ordinal selection.
    #
    # These patterns remain catalog-agnostic: they only resolve the
    # candidate position. Product identity is still taken exclusively
    # from product_search_results.
    multilingual_ordinals = {
        1: (
            r"\b(?:pehla|pahla|pehli|pahli)\s+"
            r"(?:wala|waala|wali|option|product|item)\b",
            r"(?:पहला|पहली)\s+(?:वाला|वाली|ऑप्शन|प्रोडक्ट|आइटम)",
        ),
        2: (
            r"\b(?:dusra|doosra|dusri|doosri)\s+"
            r"(?:wala|waala|wali|option|product|item)\b",
            r"(?:दूसरा|दूसरी)\s+(?:वाला|वाली|ऑप्शन|प्रोडक्ट|आइटम)",
        ),
        3: (
            r"\b(?:teesra|tisra|teesri|tisri)\s+"
            r"(?:wala|waala|wali|option|product|item)\b",
            r"(?:तीसरा|तीसरी)\s+(?:वाला|वाली|ऑप्शन|प्रोडक्ट|आइटम)",
        ),
        4: (
            r"\b(?:chautha|choutha|chauthi|chouthi)\s+"
            r"(?:wala|waala|wali|option|product|item)\b",
            r"(?:चौथा|चौथी)\s+(?:वाला|वाली|ऑप्शन|प्रोडक्ट|आइटम)",
        ),
        5: (
            r"\b(?:paanchva|panchva|panchwan|paanchwan|paanchvi)\s+"
            r"(?:wala|waala|wali|option|product|item)\b",
            r"(?:पाँचवाँ|पांचवाँ|पाँचवी|पांचवी)\s+"
            r"(?:वाला|वाली|ऑप्शन|प्रोडक्ट|आइटम)",
        ),
    }

    for index, patterns_for_index in multilingual_ordinals.items():
        for pattern in patterns_for_index:
            if re.search(pattern, text, flags=re.IGNORECASE):
                return index

    return None


def _select_product_search_result(
    message: str,
    product_search_results: list[dict[str, Any]] | None,
) -> Optional[dict[str, Any]]:
    """
    Resolve an explicit ordinal/option selection against backend-derived
    product search candidates.

    It returns only an existing candidate from product_search_results.
    """
    if not product_search_results:
        return None

    index = _selection_index_from_message(message)
    if index is None:
        return None

    zero_based = index - 1

    if zero_based < 0 or zero_based >= len(product_search_results):
        return None

    candidate = product_search_results[zero_based]

    if not isinstance(candidate, dict):
        return None

    return dict(candidate)


# =========================================================
# Product Fallback
# =========================================================


def detect_product_fallback(
    message: str,
    conversation_history: list[dict[str, Any]] | None,
) -> Optional[str]:
    """
    Recover a product from an earlier USER turn when the current turn is
    only a checkout continuation.

    Reuses detect_product_from_message() so current-turn and history
    extraction have identical language coverage.
    """
    current = (message or "").strip()

    continuation_only = (
        detect_quantity(current) is not None
        or detect_payment_method(current) is not None
        or detect_address_id(current) is not None
        or bool(detect_address_text(current))
        or bool(
            re.fullmatch(
                r"\s*(?:home|work|office|selected(?:\s+delivery)?\s+address|"
                r"use\s+(?:the\s+)?selected\s+address|"
                r"that\s+address|this\s+address)\s*",
                current,
                flags=re.IGNORECASE,
            )
        )
    )

    if not continuation_only:
        return None

    for _, content in reversed(get_user_history(conversation_history)):
        candidate = detect_product_from_message(content)
        if candidate:
            return candidate

    return None


