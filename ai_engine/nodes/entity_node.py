# =========================================================
# BuyQK AI - Entity / Understanding Node
# =========================================================
#
# Phase 2 responsibility:
#
#   User Message
#        ↓
#   AI Understanding
#        ↓
#   Current-turn entities
#        ↓
#   Accumulated transaction state
#        ↓
#   GraphState
#
# This node is an UNDERSTANDING layer.
#
# It must NOT decide:
#
#   - which tool should execute
#   - whether an order should be created
#   - whether an order should be cancelled
#   - whether an order should be tracked
#   - whether a conversational response should end
#
# Those decisions belong to planner_node.py.
#
# This node may understand:
#
#   - product references
#   - quantity
#   - order references
#   - address references
#   - payment references
#   - language/context
#   - current-turn intent
#   - references to previous conversation
#
# Backend remains authoritative for:
#
#   - product_id
#   - price
#   - stock
#   - order_id generated by backend
#   - bill
#   - payment validity
#   - address authorization
#   - order status
#
# =========================================================


