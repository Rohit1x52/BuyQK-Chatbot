def _is_quantity_only_message(message: str) -> bool:
    """Return True only when the message is a quantity reply."""
    text = re.sub(r"\s+", " ", (message or "").strip())
    if not text:
        return False

    if re.fullmatch(r"\d+", text):
        return True

    return any(
        re.fullmatch(pattern, text, flags=re.IGNORECASE)
        for pattern in (
            r"\d+(?:\.\d+)?\s*(?:packets?|packs?|pieces?|pcs?|items?|units?)",
            r"\d+(?:\.\d+)?\s*(?:kg|kgs|kilograms?|l|litres?|liters?)",
            r"\d+(?:\.\d+)?\s*(?:g|grams?)",
            r"(?:quantity|qty)\s*(?:is|=|:)?\s*\d+",
            r"make\s+it\s+\d+",
            r"change\s+(?:it\s+)?to\s+\d+",
            r"(?:want|need|like)\s+\d+",
        )
    )


def _is_selected_address_message(message: str) -> bool:
    return bool(
        re.fullmatch(
            r"\s*(?:use\s+)?(?:the\s+)?selected\s+(?:delivery\s+)?address\.?\s*",
            message or "",
            flags=re.IGNORECASE,
        )
    )


def _is_payment_only_message(message: str) -> bool:
    text = (message or "").strip()
    if not text:
        return False

    return bool(
        re.fullmatch(
            r"\s*(?:upi|cod|cash\s+on\s+delivery|"
            r"pay\s+(?:by|via)\s+(?:upi|cod)|"
            r"i\s+(?:want|would\s+like)\s+to\s+pay\s+(?:by|via)\s+(?:upi|cod))\s*",
            text,
            flags=re.IGNORECASE,
        )
    )


def _is_address_only_message(message: str) -> bool:
    text = (message or "").strip()
    if not text:
        return False

    if _is_selected_address_message(text):
        return True

    if detect_address_id(text) is not None:
        return True

    return detect_address_text(text) is not None


def _is_continuation_only_message(message: str) -> bool:
    """True only for messages safely resolvable without semantic extraction."""
    return (
        _is_quantity_only_message(message)
        or _is_payment_only_message(message)
        or _is_address_only_message(message)
    )


