# =========================================================
# Payment Detection
# =========================================================


def detect_payment_method(
    message: str,
) -> Optional[str]:

    if not message:
        return None

    text = (
        message
        .strip()
        .lower()
    )

    # UPI
    if re.search(
        r"\bupi\b",
        text,
    ):
        return "upi"

    # COD
    if (
        "cash on delivery" in text
        or re.search(
            r"\bcod\b",
            text,
        )
    ):
        return "cod"

    return None


