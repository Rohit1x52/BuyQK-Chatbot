def _safe_role(item: dict[str, Any]) -> str:
    return str(
        item.get("role", "")
    ).strip().lower()


def _safe_content(item: dict[str, Any]) -> str:
    return str(
        item.get("content", "")
    ).strip()


def format_conversation_history(
    conversation_history: list[dict[str, Any]] | None,
) -> str:
    """
    Format conversation history for the LLM.
    """

    if not conversation_history:
        return "No previous conversation."

    lines: list[str] = []

    for item in conversation_history:

        role = _safe_role(item)

        content = _safe_content(item)

        if not content:
            continue

        lines.append(
            f"{role.upper()}: {content}"
        )

    if not lines:
        return "No previous conversation."

    return "\n".join(lines)


def get_user_history(
    conversation_history: list[dict[str, Any]] | None,
) -> list[tuple[int, str]]:
    """
    Return only user messages.

    This is extremely important.

    We should NOT recover quantities from assistant messages,
    because assistant messages may contain questions such as:

        "How much would you like?"

    or examples containing numbers.
    """

    result: list[tuple[int, str]] = []

    if not conversation_history:
        return result

    for index, item in enumerate(
        conversation_history
    ):

        role = _safe_role(item)

        content = _safe_content(item)

        if role in {
            "user",
            "human",
        } and content:

            result.append(
                (index, content)
            )

    return result


def get_previous_assistant_message(
    conversation_history: list[dict[str, Any]] | None,
    user_index: int,
) -> str:
    """
    Find the assistant message immediately preceding
    a particular user message.
    """

    if not conversation_history:
        return ""

    for index in range(
        user_index - 1,
        -1,
        -1,
    ):

        item = conversation_history[index]

        role = _safe_role(item)

        if role in {
            "assistant",
            "ai",
        }:

            return _safe_content(item)

    return ""


# =========================================================
# Basic Helpers
# =========================================================


def _has_value(
    value: Any,
) -> bool:
    if value is None:
        return False

    if isinstance(value, str):
        return bool(value.strip())

    return True


def _normalize_text(
    value: Any,
) -> Optional[str]:

    if value is None:
        return None

    text = str(value).strip()

    return text if text else None


# =========================================================
# Quantity Detection
# =========================================================


def detect_quantity(
    message: str,
    allow_plain_number: bool = True,
) -> Optional[int]:
    """
    Detect explicit quantity from a message.

    Examples:

        3 packets
        2 kg
        quantity 4
        qty = 5
        make it 6
        change it to 7
        want 3

    Plain numbers are supported for direct user replies:

        3
        5
    """

    if not message:
        return None

    patterns = [
        # 3 packets
        r"\b(\d+)\s*(?:packets?|packs?|pieces?|pcs?|items?|units?)\b",

        # 3 kg / 3 kilograms
        r"\b(\d+)\s*(?:kg|kgs|kilograms?)\b",

        # 3 grams
        r"\b(\d+)\s*(?:g|grams?)\b",

        # quantity 3
        r"\b(?:quantity|qty)\s*(?:is|=|:)?\s*(\d+)\b",

        # make it 5
        r"\bmake\s+it\s+(\d+)\b",

        # change it to 5
        r"\bchange\s+(?:it\s+)?to\s+(\d+)\b",

        # want 3
        r"\b(?:want|need|like)\s+(\d+)\b",
    ]

    if allow_plain_number:
        patterns.append(
            r"^\s*(\d+)\s*$"
        )

    for pattern in patterns:

        match = re.search(
            pattern,
            message,
            flags=re.IGNORECASE,
        )

        if not match:
            continue

        try:

            value = int(
                match.group(1)
            )

            if value > 0:
                return value

        except (
            TypeError,
            ValueError,
        ):
            continue

    return None


# =========================================================
# Recover Quantity From Previous User Turns
# =========================================================


def recover_quantity_from_history(
    conversation_history: list[dict[str, Any]] | None,
) -> Optional[int]:
    """
    Recover the latest quantity supplied by the USER.

    This fixes the main bug:

        User: I want Amul milk
        Assistant: How much?
        User: 3 packets
        Assistant: Choose address
        User: Use selected address

    On the final turn, the current message contains no
    quantity. Therefore quantity must be recovered from
    the earlier user turn.
    """

    user_messages = get_user_history(
        conversation_history
    )

    if not user_messages:
        return None

    # -----------------------------------------------------
    # First pass:
    # Strong quantity expressions.
    # -----------------------------------------------------

    for _, content in reversed(
        user_messages
    ):

        value = detect_quantity(
            content,
            allow_plain_number=False,
        )

        if value is not None:
            return value

    # -----------------------------------------------------
    # Second pass:
    # A plain numeric answer is valid when the assistant
    # immediately before it asked for quantity.
    # -----------------------------------------------------

    for index, content in reversed(
        user_messages
    ):

        if not re.fullmatch(
            r"\s*\d+\s*",
            content,
        ):
            continue

        assistant_message = (
            get_previous_assistant_message(
                conversation_history,
                index,
            )
            .lower()
        )

        quantity_question = any(
            phrase in assistant_message
            for phrase in (
                "how much",
                "how many",
                "quantity",
                "how many packets",
                "how many pieces",
                "how many items",
                "what quantity",
            )
        )

        if not quantity_question:
            continue

        value = detect_quantity(
            content,
            allow_plain_number=True,
        )

        if value is not None:
            return value

    return None


# =========================================================
# Address Text Detection
# =========================================================


def detect_address_text(
    message: str,
) -> Optional[str]:

    if not message:
        return None

    patterns = [
        r"(?:my\s+)?(?:delivery\s+)?address\s+(?:is|:)\s*(.+)",

        r"(?:deliver|delivery)\s+(?:it\s+)?to\s+(.+)",

        r"(?:send|ship)\s+(?:it\s+)?to\s+(.+)",
    ]

    for pattern in patterns:

        match = re.search(
            pattern,
            message,
            flags=re.IGNORECASE,
        )

        if not match:
            continue

        value = (
            match.group(1)
            .strip()
            .rstrip(".")
        )

        if value:
            return value

    return None


# =========================================================
# Address ID Detection
# =========================================================


def detect_address_id(
    message: str,
) -> Optional[int]:

    if not message:
        return None

    match = re.search(
        r"\baddress\s*(?:id)?\s*[:#]?\s*(\d+)\b",
        message,
        flags=re.IGNORECASE,
    )

    if not match:
        return None

    try:

        value = int(
            match.group(1)
        )

        return (
            value
            if value > 0
            else None
        )

    except ValueError:

        return None


